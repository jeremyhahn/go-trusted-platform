// VMSnapshot describes an internal QEMU snapshot of a VM instance. Internal
// snapshots capture the full VM state — memory and disk — inside the
// instance's qcow2 image.
type VMSnapshot struct {
	// Name is the snapshot tag (QEMU savevm tag).
	Name string `json:"name"`

	// VMID is the compute instance the snapshot belongs to.
	VMID string `json:"vm_id"`

	// CreatedAt is when the snapshot was created.
	CreatedAt time.Time `json:"created_at"`

	// SizeBytes is the size of the saved VM state in bytes.
	SizeBytes int64 `json:"size_bytes"`

	// Description is optional human-readable metadata. Internal QEMU
	// snapshots do not persist descriptions; the field exists for
	// transports that carry one.
	Description string `json:"description,omitempty"`
}

// VMSuspender is implemented by orchestrators that can pause a running VM
// in memory and continue it later. The QEMU orchestrator does it over the
// QMP monitor (stop / cont). Protocol surfaces type-assert this interface on
// the compute Orchestrator and reject the operation with a typed error when
// the capability is absent.
type VMSuspender interface {
	// Suspend pauses a running VM. It returns ErrInstanceNotRunning when
	// the VM is not running.
	Suspend(ctx context.Context, instanceID string) error

	// Resume continues a suspended VM. It returns ErrInstanceNotSuspended
	// when the VM is not suspended.
	Resume(ctx context.Context, instanceID string) error
}

// VMSnapshotter is the capability interface for internal (qcow2) VM
// snapshots. Orchestrators that manage QEMU virtual machines implement it;
// container orchestrators do not. Protocol surfaces type-assert this
// interface on the compute Orchestrator and reject the operation with a
// typed error when the capability is absent.
//
// Internal snapshots are executed over the VM's QMP monitor (savevm /
// loadvm / delvm), which requires a running VM and a qcow2 disk image.
type VMSnapshotter interface {
	// CreateSnapshot creates an internal snapshot capturing memory + disk.
	CreateSnapshot(ctx context.Context, instanceID, snapshotName string) (*VMSnapshot, error)

	// RestoreSnapshot restores the VM to a previously created snapshot.
	RestoreSnapshot(ctx context.Context, instanceID, snapshotName string) error

	// DeleteSnapshot removes a snapshot from the VM's disk image.
	DeleteSnapshot(ctx context.Context, instanceID, snapshotName string) error

	// ListSnapshots lists all snapshots for the VM.
	ListSnapshots(ctx context.Context, instanceID string) ([]*VMSnapshot, error)
}

// VMAttestationReport carries the result of a vTPM quote generated for a VM
// instance.
type VMAttestationReport struct {
	// VMID is the attested compute instance ID.
	VMID string `json:"vm_id"`

	// VMName is the instance name.
	VMName string `json:"vm_name"`

	// Timestamp is when the quote was generated.
	Timestamp time.Time `json:"timestamp"`

	// Verified reports whether the platform verified the quote. Quote
	// generation returns false; verification is a distinct step
	// (VerifyVMAttestation).
	Verified bool `json:"verified"`

	// Nonce is the anti-replay nonce embedded in the quote (caller
	// supplied, or generated by the platform when the caller omitted one).
	Nonce []byte `json:"nonce,omitempty"`

	// PCRValues maps PCR index to its SHA-256 value at quote time.
	PCRValues map[int][]byte `json:"pcr_values,omitempty"`

	// Quote is the marshaled TPMS_ATTEST structure.
	Quote []byte `json:"quote,omitempty"`

	// Signature is the AK signature over the quote.
	Signature []byte `json:"signature,omitempty"`

	// SignatureAlgorithm is the x509.SignatureAlgorithm name of the scheme
	// the AK signed the quote under (for example "SHA256-RSAPSS"). The
	// signature is bare bytes, so a verifier needs it to check the quote.
	SignatureAlgorithm string `json:"signature_algorithm,omitempty"`

	// EventLog is the measurement log, when available.
	EventLog []byte `json:"event_log,omitempty"`

	// AKPublicKey is the DER (PKIX) encoding of the attestation key
	// public key that signed the quote.
	AKPublicKey []byte `json:"ak_public_key,omitempty"`
}

// VMAttestationEvidence carries quote evidence submitted for verification.
type VMAttestationEvidence struct {
	// Quote is the marshaled TPMS_ATTEST structure.
	Quote []byte

	// Signature is the AK signature over the quote.
	Signature []byte

	// SignatureAlgorithm is the scheme the quote declares it was signed
	// under, as reported by AttestVM. The quote is verified under it alone;
	// an absent or unknown scheme fails verification.
	SignatureAlgorithm string

	// Nonce is the expected anti-replay nonce.
	Nonce []byte

	// ExpectedPCRs maps PCR index to the expected SHA-256 value. When
	// provided, the index set must exactly match the quote's PCR
	// selection.
	ExpectedPCRs map[int][]byte
}

// VMVerificationResult reports the outcome of VM attestation verification.
type VMVerificationResult struct {
	// Verified is true when every verification step passed.
	Verified bool `json:"verified"`

	// SignatureValid reports whether the AK signature over the quote is
	// valid.
	SignatureValid bool `json:"signature_valid"`

	// NonceValid reports whether the quote embeds the expected nonce.
	NonceValid bool `json:"nonce_valid"`

	// PCRsValid reports whether the quote's PCR digest matches the
	// expected PCR values (true when no expected PCRs were supplied).
	PCRsValid bool `json:"pcrs_valid"`

	// Message summarizes the verification outcome.
	Message string `json:"message,omitempty"`

	// ActualPCRs contains the live PCR values read from the instance's
	// vTPM for the expected PCR indices (diagnostics).
	ActualPCRs map[int][]byte `json:"actual_pcrs,omitempty"`
}

// VMAttester is the capability interface for vTPM quote attestation of VM
// instances. Orchestrators that provision a per-instance vTPM (swtpm)
// implement it. Protocol surfaces type-assert this interface on the compute
// Orchestrator and reject the operation with a typed error when the
// capability is absent.
type VMAttester interface {
	// AttestVM generates a TPM quote from the instance's vTPM. A nil or
	// empty nonce is replaced with a platform-generated random nonce; an
	// empty PCR selection defaults to PCRs 0-7. Only the SHA-256 bank is
	// supported.
	AttestVM(ctx context.Context, instanceID string, nonce []byte, pcrIndices []int) (*VMAttestationReport, error)

	// VerifyVMAttestation verifies quote evidence against the instance's
	// live vTPM attestation key: AK signature over the quote, embedded
	// nonce, and (when expected PCRs are supplied) the quote's PCR digest.
	VerifyVMAttestation(ctx context.Context, instanceID string, evidence *VMAttestationEvidence) (*VMVerificationResult, error)
}
