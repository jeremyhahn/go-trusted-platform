// RCGenerator generates OpenRC-compatible init scripts for container services.
// It creates properly formatted init scripts with all necessary functions
// for managing containers as OpenRC services.
type RCGenerator struct {
	// podmanPath is the path to the podman binary
	podmanPath string

	// pidDir is the directory for PID files
	pidDir string
}

// NewRCGenerator creates a new RCGenerator with default settings
func NewRCGenerator() *RCGenerator {
	return &RCGenerator{
		podmanPath: "/usr/bin/podman",
		pidDir:     "/run",
	}
}

// RCGeneratorOption configures an RCGenerator
type RCGeneratorOption func(*RCGenerator)

// WithRCPodmanPath sets a custom path to the podman binary
func WithRCPodmanPath(path string) RCGeneratorOption {
	return func(g *RCGenerator) {
		g.podmanPath = path
	}
}

// WithRCPidDir sets a custom PID directory
func WithRCPidDir(dir string) RCGeneratorOption {
	return func(g *RCGenerator) {
		g.pidDir = dir
	}
}

// NewRCGeneratorWithOptions creates a new RCGenerator with options
func NewRCGeneratorWithOptions(opts ...RCGeneratorOption) *RCGenerator {
	g := NewRCGenerator()
	for _, opt := range opts {
		opt(g)
	}
	return g
}

// Generate generates an OpenRC init script for the given container
// specification.
//
// The script starts the container's effective launch configuration — the same
// value newLaunchConfig derives for the embedded path and AttestationSpec
// measures — so a standalone container is the container that was measured. The
// specification is read only to derive that value; the script's supervision
// settings come from spec.Service.
func (g *RCGenerator) Generate(spec *OrchestratorContainerSpec) string {
	if spec == nil {
		return ""
	}
	return g.generate(newLaunchConfig(spec), &spec.Service)
}

// GenerateFromContainerConfig generates an OpenRC init script for a
// ContainerConfig, through the same single derivation as Generate.
func (g *RCGenerator) GenerateFromContainerConfig(container *ContainerConfig) string {
	if container == nil {
		return ""
	}
	return g.generate(newLaunchConfig(container.ToOrchestratorContainerSpec()), &container.Service)
}

// generate writes the init script for an effective launch configuration.
func (g *RCGenerator) generate(launch *PodmanContainerConfig, service *ServiceConfig) string {
	var builder strings.Builder

	g.writeHeader(&builder, launch.Name)
	g.writeVariables(&builder, launch)
	g.writeDependFunction(&builder, service)
	g.writeStartFunction(&builder, launch)
	g.writeStopFunction(&builder, launch)
	g.writeStatusFunction(&builder)

	return builder.String()
}

// writeHeader writes the shebang and header comments
func (g *RCGenerator) writeHeader(builder *strings.Builder, name string) {
	builder.WriteString("#!/sbin/openrc-run\n")
	builder.WriteString("# OpenRC init script for container service\n")
	fmt.Fprintf(builder, "# Container: %s\n", name)
	builder.WriteString("# Generated by go-trusted-platform\n")
	builder.WriteString("# https://github.com/jeremyhahn/go-trusted-platform\n")
	builder.WriteString("\n")
}

// writeVariables writes the variable definitions used by the lifecycle
// functions. The container's launch arguments are not among them: they are
// emitted directly into start(), already quoted, because a shell variable
// expanded unquoted would be re-split on whitespace and would hand podman
// something other than the measured argument vector.
func (g *RCGenerator) writeVariables(builder *strings.Builder, launch *PodmanContainerConfig) {
	builder.WriteString("# Configuration\n")
	fmt.Fprintf(builder, "name=%s\n", shellDoubleQuoted("container-"+launch.Name))
	fmt.Fprintf(builder, "description=%s\n",
		shellDoubleQuoted("Container "+launch.Name+" managed by go-trusted-platform"))
	fmt.Fprintf(builder, "podman=%s\n", shellDoubleQuoted(g.podmanPath))
	fmt.Fprintf(builder, "container_name=%s\n", shellDoubleQuoted(launch.Name))
	fmt.Fprintf(builder, "container_image=%s\n", shellDoubleQuoted(launch.Image))
	fmt.Fprintf(builder, "pidfile=%s\n",
		shellDoubleQuoted(g.pidDir+"/container-"+launch.Name+".pid"))
	builder.WriteString("\n")
}

// writeDependFunction writes the depend() function
func (g *RCGenerator) writeDependFunction(builder *strings.Builder, service *ServiceConfig) {
	builder.WriteString("depend() {\n")

	// Need dependencies
	needDeps := []string{"net"}
	fmt.Fprintf(builder, "    need %s\n", strings.Join(needDeps, " "))

	// Use dependencies (soft dependencies)
	useDeps := []string{"dns", "logger"}
	if service != nil && service.Standalone != nil {
		// Add custom After dependencies as use dependencies
		for _, dep := range service.Standalone.After {
			// Convert systemd target names to OpenRC service names
			useDeps = append(useDeps, g.convertSystemdToRC(dep))
		}
	}
	fmt.Fprintf(builder, "    use %s\n", strings.Join(useDeps, " "))

	// After dependencies
	afterDeps := []string{"firewall"}
	fmt.Fprintf(builder, "    after %s\n", strings.Join(afterDeps, " "))

	builder.WriteString("}\n")
	builder.WriteString("\n")
}

// writeStartFunction writes the start() function, which runs the measured
// launch configuration.
func (g *RCGenerator) writeStartFunction(builder *strings.Builder, launch *PodmanContainerConfig) {
	builder.WriteString("start() {\n")
	builder.WriteString("    ebegin \"Starting ${name}\"\n")
	builder.WriteString("\n")

	// Pull the image first (ignore errors if already exists)
	builder.WriteString("    # Pull the container image\n")
	builder.WriteString("    ${podman} pull \"${container_image}\" 2>/dev/null || true\n")
	builder.WriteString("\n")

	// Remove any existing container with the same name
	builder.WriteString("    # Remove any existing container with the same name\n")
	builder.WriteString("    ${podman} rm -f \"${container_name}\" 2>/dev/null || true\n")
	builder.WriteString("\n")

	// Start the container from its effective launch configuration
	builder.WriteString("    # Start the container. The argument vector is the container's\n")
	builder.WriteString("    # effective launch configuration, which is what was measured.\n")
	fmt.Fprintf(builder, "    ${podman} run -d %s\n", shellCommand(podmanRunArgs(launch)))
	builder.WriteString("\n")

	// Get the container PID and write it
	builder.WriteString("    # Get container PID\n")
	builder.WriteString("    local container_pid\n")
	builder.WriteString("    container_pid=$(${podman} inspect --format '{{.State.Pid}}' \"${container_name}\" 2>/dev/null)\n")
	builder.WriteString("    if [ -n \"${container_pid}\" ] && [ \"${container_pid}\" != \"0\" ]; then\n")
	builder.WriteString("        echo \"${container_pid}\" > \"${pidfile}\"\n")
	builder.WriteString("    fi\n")
	builder.WriteString("\n")

	builder.WriteString("    eend $?\n")
	builder.WriteString("}\n")
	builder.WriteString("\n")
}

// writeStopFunction writes the stop() function
func (g *RCGenerator) writeStopFunction(builder *strings.Builder, launch *PodmanContainerConfig) {
	builder.WriteString("stop() {\n")
	builder.WriteString("    ebegin \"Stopping ${name}\"\n")
	builder.WriteString("\n")

	// Stop the container on the launch configuration's schedule
	builder.WriteString("    # Stop the container\n")
	fmt.Fprintf(builder, "    ${podman} stop -t %d \"${container_name}\" 2>/dev/null\n",
		effectiveStopTimeout(launch))
	builder.WriteString("\n")

	// Remove the container
	builder.WriteString("    # Remove the container\n")
	builder.WriteString("    ${podman} rm -f \"${container_name}\" 2>/dev/null || true\n")
	builder.WriteString("\n")

	// Remove PID file
	builder.WriteString("    # Remove PID file\n")
	builder.WriteString("    rm -f \"${pidfile}\"\n")
	builder.WriteString("\n")

	builder.WriteString("    eend $?\n")
	builder.WriteString("}\n")
	builder.WriteString("\n")
}

// writeStatusFunction writes the status() function
func (g *RCGenerator) writeStatusFunction(builder *strings.Builder) {
	builder.WriteString("status() {\n")
	builder.WriteString("    # Check if container is running\n")
	builder.WriteString("    if ${podman} inspect \"${container_name}\" >/dev/null 2>&1; then\n")
	builder.WriteString("        local state\n")
	builder.WriteString("        state=$(${podman} inspect --format '{{.State.Status}}' \"${container_name}\" 2>/dev/null)\n")
	builder.WriteString("        if [ \"${state}\" = \"running\" ]; then\n")
	builder.WriteString("            einfo \"${name} is running\"\n")
	builder.WriteString("            return 0\n")
	builder.WriteString("        else\n")
	builder.WriteString("            ewarn \"${name} is ${state}\"\n")
	builder.WriteString("            return 1\n")
	builder.WriteString("        fi\n")
	builder.WriteString("    else\n")
	builder.WriteString("        einfo \"${name} is stopped\"\n")
	builder.WriteString("        return 3\n")
	builder.WriteString("    fi\n")
	builder.WriteString("}\n")
}

// convertSystemdToRC converts systemd target/service names to OpenRC equivalents
func (g *RCGenerator) convertSystemdToRC(name string) string {
	// Remove .target and .service suffixes
	name = strings.TrimSuffix(name, ".target")
	name = strings.TrimSuffix(name, ".service")

	// Map common systemd names to OpenRC
	mapping := map[string]string{
		"network-online": "net",
		"network":        "net",
		"syslog":         "logger",
		"local-fs":       "localmount",
		"remote-fs":      "netmount",
		"time-sync":      "ntp-client",
	}

	if rcName, ok := mapping[name]; ok {
		return rcName
	}

	return name
}

// shellDoubleQuoted renders a value as a double-quoted shell string, escaping
// the characters a shell would otherwise interpret inside one. It is for the
// script's own variable assignments; command arguments use shellArg, whose
// single-quoted form suppresses every expansion.
func shellDoubleQuoted(value string) string {
	var b strings.Builder
	b.Grow(len(value) + 2)
	b.WriteByte('"')
	for _, r := range value {
		switch r {
		case '\\', '"', '$', '`':
			b.WriteByte('\\')
		}
		b.WriteRune(r)
	}
	b.WriteByte('"')
	return b.String()
}

// GenerateRCScript is a convenience function that generates an OpenRC init
// script for the given container specification.
func GenerateRCScript(spec *OrchestratorContainerSpec) string {
	g := NewRCGenerator()
	return g.Generate(spec)
}
