// TestRCGenerator_Generate tests generating an OpenRC init script
func TestRCGenerator_Generate(t *testing.T) {
	g := NewRCGenerator()

	spec := &OrchestratorContainerSpec{
		Name:  "test-container",
		Image: "docker.io/library/nginx:latest",
	}

	result := g.Generate(spec)

	// Verify shebang
	if !strings.HasPrefix(result, "#!/sbin/openrc-run") {
		t.Error("Generated script missing shebang")
	}

	// Verify header comments
	if !strings.Contains(result, "# Container: test-container") {
		t.Error("Generated script missing container name in header")
	}
	if !strings.Contains(result, "# Generated by go-trusted-platform") {
		t.Error("Generated script missing generator comment")
	}

	// Verify variables
	if !strings.Contains(result, `name="container-test-container"`) {
		t.Error("Generated script missing name variable")
	}
	if !strings.Contains(result, `container_image="docker.io/library/nginx:latest"`) {
		t.Error("Generated script missing image variable")
	}
	if !strings.Contains(result, `pidfile="/run/container-test-container.pid"`) {
		t.Error("Generated script missing pidfile variable")
	}

	// Verify depend() function
	if !strings.Contains(result, "depend() {") {
		t.Error("Generated script missing depend() function")
	}
	if !strings.Contains(result, "need net") {
		t.Error("Generated script missing network dependency")
	}

	// Verify start() function
	if !strings.Contains(result, "start() {") {
		t.Error("Generated script missing start() function")
	}
	if !strings.Contains(result, "ebegin") {
		t.Error("Generated script missing ebegin")
	}
	if !strings.Contains(result, "eend") {
		t.Error("Generated script missing eend")
	}

	// Verify stop() function
	if !strings.Contains(result, "stop() {") {
		t.Error("Generated script missing stop() function")
	}

	// Verify status() function
	if !strings.Contains(result, "status() {") {
		t.Error("Generated script missing status() function")
	}
}

// TestRCGenerator_GenerateWithFullConfig tests with all options
func TestRCGenerator_GenerateWithFullConfig(t *testing.T) {
	g := NewRCGenerator()

	spec := &OrchestratorContainerSpec{
		Name:       "full-rc-test",
		Image:      "myregistry.io/myapp:v1.0",
		Command:    []string{"/app/start.sh"},
		Privileged: true,
		Env: map[string]string{
			"APP_ENV": "production",
		},
		Labels: map[string]string{
			"app": "myapp",
		},
		Ports: []PortMapping{
			{HostPort: 8080, ContainerPort: 80, Protocol: "tcp"},
			{HostPort: 9090, ContainerPort: 90, Protocol: "udp"},
		},
		Mounts: []MountConfig{
			{Source: "/host/data", Target: "/data"},
			{Source: "/host/config", Target: "/config", ReadOnly: true},
		},
		Network: ContainerNetworkConfig{
			Mode: NetworkModeHost,
		},
		Resources: ResourceConfig{
			MemoryLimit: "2G",
			CPULimit:    "2",
		},
		Service: ServiceConfig{
			Mode: ServiceModeStandalone,
			Standalone: &StandaloneConfig{
				After: []string{"network-online.target", "database.service"},
			},
		},
	}

	result := g.Generate(spec)

	// Verify privileged flag
	if !strings.Contains(result, "--privileged") {
		t.Error("Generated script missing --privileged flag")
	}

	// Verify environment variables
	if !strings.Contains(result, "-e") && !strings.Contains(result, "APP_ENV") {
		t.Error("Generated script missing environment variable")
	}

	// Verify port mappings
	if !strings.Contains(result, "-p 8080:80") {
		t.Error("Generated script missing TCP port mapping")
	}
	if !strings.Contains(result, "-p 9090:90/udp") {
		t.Error("Generated script missing UDP port mapping")
	}

	// Verify volume mounts
	if !strings.Contains(result, "-v") && !strings.Contains(result, "/host/data") {
		t.Error("Generated script missing volume mount")
	}

	// Verify network mode
	if !strings.Contains(result, "--network host") {
		t.Error("Generated script missing network mode")
	}

	// Verify resource limits
	if !strings.Contains(result, "--memory 2G") {
		t.Error("Generated script missing memory limit")
	}
}

// TestRCGenerator_ConvertSystemdToRC tests systemd to rc name conversion
func TestRCGenerator_ConvertSystemdToRC(t *testing.T) {
	g := NewRCGenerator()

	tests := []struct {
		input    string
		expected string
	}{
		{"network-online.target", "net"},
		{"network.target", "net"},
		{"syslog.service", "logger"},
		{"local-fs.target", "localmount"},
		{"remote-fs.target", "netmount"},
		{"time-sync.target", "ntp-client"},
		{"custom.service", "custom"},
		{"myapp.target", "myapp"},
	}

	for _, tt := range tests {
		t.Run(tt.input, func(t *testing.T) {
			result := g.convertSystemdToRC(tt.input)
			if result != tt.expected {
				t.Errorf("convertSystemdToRC(%q) = %q, want %q", tt.input, result, tt.expected)
			}
		})
	}
}

