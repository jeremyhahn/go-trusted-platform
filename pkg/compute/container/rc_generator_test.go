// TestNewRCGenerator tests the constructor
func TestNewRCGenerator(t *testing.T) {
	g := NewRCGenerator()

	if g == nil {
		t.Fatal("NewRCGenerator() returned nil")
	}

	if g.podmanPath != "/usr/bin/podman" {
		t.Errorf("podmanPath = %q, want %q", g.podmanPath, "/usr/bin/podman")
	}

	if g.pidDir != "/run" {
		t.Errorf("pidDir = %q, want %q", g.pidDir, "/run")
	}
}

