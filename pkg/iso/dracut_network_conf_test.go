package iso

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

// loadNetworkConf runs the shipped platformd_load_network_conf under /bin/sh on
// a network.conf with the given content and returns the variables it set (one
// per line), its stderr and its exit status.
func loadNetworkConf(t *testing.T, content string) (vars string, stderr string, exit int) {
	t.Helper()
	dir := t.TempDir()
	helper := filepath.Join(dir, "load.sh")
	conf := filepath.Join(dir, "network.conf")
	require.NoError(t, os.WriteFile(helper, []byte(platformdNetworkUpShell), 0o600))
	require.NoError(t, os.WriteFile(conf, []byte(content), 0o600))
	script := `. "$0"; platformd_load_network_conf "$1"; rc=$?
for v in INTERFACE TYPE IPV4_ADDRESS IPV4_PREFIX IPV4_NETMASK IPV4_GATEWAY DNS HOSTNAME; do
  eval "printf '%s=%s\n' $v \"\$$v\""
done
exit $rc`
	cmd := exec.Command("/bin/sh", "-c", script, helper, conf)
	var errBuf strings.Builder
	cmd.Stderr = &errBuf
	out, err := cmd.Output()
	if exitErr, ok := err.(*exec.ExitError); ok {
		exit = exitErr.ExitCode()
	} else {
		require.NoError(t, err)
	}
	return string(out), errBuf.String(), exit
}

// TestPlatformdLoadNetworkConf_ParsesWhatTheInstallerWrites loads a file shaped
// exactly like writeFirstbootNetworkConfig's output.
func TestPlatformdLoadNetworkConf_ParsesWhatTheInstallerWrites(t *testing.T) {
	vars, stderr, exit := loadNetworkConf(t, `# Firstboot network configuration
# Generated by installer for initramfs network setup

INTERFACE=eth0
TYPE=static
IPV4_ADDRESS=192.0.2.140
IPV4_PREFIX=24
IPV4_NETMASK=255.255.255.0
IPV4_GATEWAY=192.0.2.1
DNS="192.0.2.1 1.1.1.1"
HOSTNAME=node-1.example.com
`)
	assert.Equal(t, 0, exit, stderr)
	assert.Empty(t, stderr)
	assert.Equal(t, "INTERFACE=eth0\nTYPE=static\nIPV4_ADDRESS=192.0.2.140\nIPV4_PREFIX=24\n"+
		"IPV4_NETMASK=255.255.255.0\nIPV4_GATEWAY=192.0.2.1\nDNS=192.0.2.1 1.1.1.1\nHOSTNAME=node-1.example.com\n", vars)
}

// TestPlatformdLoadNetworkConf_NeverExecutesTheFile: command substitution,
// command separators, backticks and variable expansion in a value are rejected,
// never run and never applied; a key off the allow-list is ignored. The lines
// that are valid still load.
func TestPlatformdLoadNetworkConf_NeverExecutesTheFile(t *testing.T) {
	canary := filepath.Join(t.TempDir(), "ran")
	cases := map[string]string{
		"command substitution": "HOSTNAME=$(touch " + canary + ")\n",
		"separator":            "HOSTNAME=node; touch " + canary + "\n",
		"backticks":            "HOSTNAME=`touch " + canary + "`\n",
		"expansion":            "HOSTNAME=${PATH}\n",
		"quoted separator":     "DNS=\"1.1.1.1; touch " + canary + "\"\n",
		"command line":         "touch " + canary + "\n",
		"unknown key":          "PATH=/tmp\nLD_PRELOAD=/tmp/x.so\n",
	}
	for name, line := range cases {
		t.Run(name, func(t *testing.T) {
			vars, stderr, exit := loadNetworkConf(t, "INTERFACE=eth1\n"+line)
			assert.Equal(t, 1, exit, "a rejected line must fail the load")
			assert.NotEmpty(t, stderr)
			assert.Contains(t, vars, "INTERFACE=eth1\n", "valid lines still load")
			assert.Contains(t, vars, "HOSTNAME=\n", "the rejected value was applied")
			assert.Contains(t, vars, "DNS=\n", "the rejected value was applied")
			_, err := os.Stat(canary)
			assert.True(t, os.IsNotExist(err), "the file's content was executed")
		})
	}
}

// TestPlatformdLoadNetworkConf_UnterminatedLastLine: a final line with no
// newline is still read.
func TestPlatformdLoadNetworkConf_UnterminatedLastLine(t *testing.T) {
	vars, _, exit := loadNetworkConf(t, "TYPE=dhcp")
	assert.Equal(t, 0, exit)
	assert.Contains(t, vars, "TYPE=dhcp\n")
}

// TestPlatformdNetworkUpShell_DoesNotSourceTheFile guards the loader's use: the
// network-up hook calls it and never sources the file.
func TestPlatformdNetworkUpShell_DoesNotSourceTheFile(t *testing.T) {
	assert.Contains(t, platformdNetworkUpShell, `platformd_load_network_conf "$NETWORK_CONF"`)
	assert.NotContains(t, platformdNetworkUpShell, `. "$NETWORK_CONF"`)
}
