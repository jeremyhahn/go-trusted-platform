// newIAKInstallCommand creates the install subcommand for installing certificates
func newIAKInstallCommand(getFlags func() *cli.CommonFlags) *cobra.Command {
	var certFile string

	cmd := &cobra.Command{
		Use:   "install",
		Short: "Install a certificate for the IAK key",
		Long: `Install a certificate for the IAK key.

The certificate must be in PEM format and must correspond to the
existing IAK key in the TPM.

Examples:
  # Install certificate from file
  platformctl tpm iak install --cert-file /path/to/cert.pem

  # Install and verify
  platformctl tpm iak install --cert-file cert.pem && platformctl tpm iak info`,
		RunE: func(cmd *cobra.Command, args []string) error {
			flags := getFlags()
			return runIAKInstall(flags, certFile)
		},
	}

	cmd.Flags().StringVar(&certFile, "cert-file", "", "path to certificate file (PEM format)")
	cli.MarkFlagsRequired(cmd, "cert-file")

	return cmd
}

