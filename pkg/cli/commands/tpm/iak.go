// NewIAKCommand creates the iak command group for IAK key management
func NewIAKCommand(getFlags func() *cli.CommonFlags) *cobra.Command {
	cmd := &cobra.Command{
		Use:   "iak",
		Short: "Manage IAK (Initial Attestation Key) keys",
		Long: `Manage IAK keys in the TPM per TCG specifications.

IAK is the Initial Attestation Key, a restricted signing key that
can only sign data generated by the TPM itself. It is used for
remote attestation to prove the integrity of the platform.

The IAK is typically paired with an IDevID and together they provide
device identity and platform attestation capabilities.

Supported operations:
  - generate: Create a new IAK key in the TPM
  - info: Retrieve information about the existing IAK key
  - delete: Refused; the IAK is TPM-resident and is not evicted

Examples:
  # Generate IAK with default algorithm (ECDSA-P256)
  platformctl tpm iak generate

  # Generate IAK with specific algorithm
  platformctl tpm iak generate --algorithm RSA-2048

  # Overwrite existing IAK key
  platformctl tpm iak generate --algorithm ECDSA-P384 --overwrite

  # Get IAK key information
  platformctl tpm iak info

  # Get IAK info as JSON (for scripting)
  platformctl tpm iak info -o json`,
	}

	cmd.AddCommand(newIAKGenerateCommand(getFlags))
	cmd.AddCommand(newIAKInfoCommand(getFlags))
	cmd.AddCommand(newIAKDeleteCommand(getFlags))
	cmd.AddCommand(newIAKCSRCommand(getFlags))
	cmd.AddCommand(newIAKInstallCommand(getFlags))
	cmd.AddCommand(newIAKCertCommand(getFlags))

	return cmd
}

// newIAKGenerateCommand creates the generate subcommand for IAK
func newIAKGenerateCommand(getFlags func() *cli.CommonFlags) *cobra.Command {
	var algorithm string
	var overwrite bool

	cmd := &cobra.Command{
		Use:   "generate",
		Short: "Generate a new IAK key in the TPM",
		Long: `Generate a new IAK (Initial Attestation Key) key in the TPM.

The IAK is a restricted signing key created in the TPM's endorsement
hierarchy. It can only sign data generated by the TPM (quotes, certify
operations) and is used for remote attestation.

Supported algorithms:
  - ECDSA-P256 (default, recommended by TCG)
  - ECDSA-P384
  - RSA-2048
  - RSA-3072

Examples:
  # Generate with default algorithm
  platformctl tpm iak generate

  # Generate with specific algorithm
  platformctl tpm iak generate --algorithm RSA-2048

  # Overwrite existing key
  platformctl tpm iak generate --overwrite`,
		RunE: func(cmd *cobra.Command, args []string) error {
			flags := getFlags()
			return runIAKGenerate(flags, algorithm, overwrite)
		},
	}

	cmd.Flags().StringVar(&algorithm, "algorithm", "ECDSA-P256",
		"key algorithm: ECDSA-P256, ECDSA-P384, RSA-2048, RSA-3072")
	cmd.Flags().BoolVar(&overwrite, "overwrite", false,
		"overwrite existing IAK key if present")

	return cmd
}

