// secretsStatusFlags contains flags for the status command
type secretsStatusFlags struct {
	configPath string
	showURIs   bool
}

// newSecretsStatusCommand creates the secrets status command
func newSecretsStatusCommand(getFlags func() *cli.CommonFlags) *cobra.Command {
	cmdFlags := &secretsStatusFlags{}

	cmd := &cobra.Command{
		Use:   "status",
		Short: "Show secret resolution status",
		Long: `Display the status of all secret URIs in the configuration file.

This command scans the configuration file and reports:
  - Total number of secrets found
  - Secret URIs grouped by scheme (kms://, env://, etc.)
  - Which resolvers are available for each scheme
  - Any potentially unresolvable secrets

Examples:
  # Show secret status
  platformctl bootstrap secrets status --config /etc/trusted-platform/config.yaml

  # Show status with full URIs (masked)
  platformctl bootstrap secrets status --config /etc/trusted-platform/config.yaml --show-uris`,
		RunE: func(cmd *cobra.Command, args []string) error {
			flags := getFlags()
			return runSecretsStatus(flags, cmdFlags)
		},
	}

	cmd.Flags().StringVar(&cmdFlags.configPath, "config", "", "Path to configuration file (required)")
	cmd.Flags().BoolVar(&cmdFlags.showURIs, "show-uris", false, "Show masked secret URIs")

	cmd.MarkFlagRequired("config") //nolint:errcheck

	return cmd
}

// secretSchemeStats tracks statistics for a secret scheme
type secretSchemeStats struct {
	scheme    string
	count     int
	available bool
	secrets   []secretInfo
}

// runSecretsStatus executes the secrets status command
func runSecretsStatus(flags *cli.CommonFlags, cmdFlags *secretsStatusFlags) error {
	if cmdFlags.configPath == "" {
		return ErrConfigPathRequired{}
	}

	base, err := cli.NewBaseCommand(flags)
	if err != nil {
		return err
	}
	defer base.Close()

	printer := base.Printer()

	// Read configuration file
	configData, err := os.ReadFile(cmdFlags.configPath)
	if err != nil {
		return ErrConfigFileReadFailed{Path: cmdFlags.configPath, Err: err}
	}

	// Scan for secrets
	secrets := scanConfigForSecrets(configData)

	// Group by scheme
	schemeStats := make(map[string]*secretSchemeStats)
	for _, secret := range secrets {
		scheme := detectScheme(secret.uri)
		if _, exists := schemeStats[scheme]; !exists {
			schemeStats[scheme] = &secretSchemeStats{
				scheme:    scheme,
				available: isResolverAvailable(scheme),
				secrets:   make([]secretInfo, 0),
			}
		}
		schemeStats[scheme].count++
		schemeStats[scheme].secrets = append(schemeStats[scheme].secrets, secret)
	}

	// Count categories
	var kmsCount, envCount, autoGenCount, remoteKMSCount, encryptedCount, unknownCount int
	for scheme, stats := range schemeStats {
		switch scheme {
		case "kms":
			kmsCount = stats.count
		case "env":
			envCount = stats.count
		case "autogen":
			autoGenCount = stats.count
		case "remote-kms":
			remoteKMSCount = stats.count
		case "encrypted":
			encryptedCount = stats.count
		default:
			unknownCount += stats.count
		}
	}

	switch flags.OutputFormat {
	case cli.OutputFormatJSON, cli.OutputFormatYAML:
		result := struct {
			ConfigPath string `json:"config_path" yaml:"config_path"`
			Summary    struct {
				TotalSecrets  int `json:"total_secrets" yaml:"total_secrets"`
				KMSManaged    int `json:"kms_managed" yaml:"kms_managed"`
				Environment   int `json:"environment" yaml:"environment"`
				AutoGenerated int `json:"auto_generated" yaml:"auto_generated"`
				RemoteKMS     int `json:"remote_kms" yaml:"remote_kms"`
				Encrypted     int `json:"encrypted" yaml:"encrypted"`
				Unknown       int `json:"unknown" yaml:"unknown"`
			} `json:"summary" yaml:"summary"`
			Schemes []struct {
				Name      string   `json:"name" yaml:"name"`
				Count     int      `json:"count" yaml:"count"`
				Available bool     `json:"available" yaml:"available"`
				Paths     []string `json:"paths,omitempty" yaml:"paths,omitempty"`
			} `json:"schemes" yaml:"schemes"`
		}{
			ConfigPath: cmdFlags.configPath,
		}
		result.Summary.TotalSecrets = len(secrets)
		result.Summary.KMSManaged = kmsCount
		result.Summary.Environment = envCount
		result.Summary.AutoGenerated = autoGenCount
		result.Summary.RemoteKMS = remoteKMSCount
		result.Summary.Encrypted = encryptedCount
		result.Summary.Unknown = unknownCount

		for scheme, stats := range schemeStats {
			schemeInfo := struct {
				Name      string   `json:"name" yaml:"name"`
				Count     int      `json:"count" yaml:"count"`
				Available bool     `json:"available" yaml:"available"`
				Paths     []string `json:"paths,omitempty" yaml:"paths,omitempty"`
			}{
				Name:      scheme,
				Count:     stats.count,
				Available: stats.available,
			}
			if cmdFlags.showURIs {
				for _, s := range stats.secrets {
					schemeInfo.Paths = append(schemeInfo.Paths, s.path)
				}
			}
			result.Schemes = append(result.Schemes, schemeInfo)
		}

		return printer.Print(result)

	default:
		// Table output
		printer.PrintKeyValue("Configuration", cmdFlags.configPath)
		fmt.Println()

		// Summary
		printer.PrintInfo("Secret Summary")
		printer.PrintKeyValue("  Total secrets", fmt.Sprintf("%d", len(secrets)))
		if kmsCount > 0 {
			printer.PrintKeyValue("  KMS managed", fmt.Sprintf("%d", kmsCount))
		}
		if envCount > 0 {
			printer.PrintKeyValue("  Environment", fmt.Sprintf("%d", envCount))
		}
		if autoGenCount > 0 {
			printer.PrintKeyValue("  Auto-generated", fmt.Sprintf("%d", autoGenCount))
		}
		if remoteKMSCount > 0 {
			printer.PrintKeyValue("  Remote KMS", fmt.Sprintf("%d", remoteKMSCount))
		}
		if encryptedCount > 0 {
			printer.PrintKeyValue("  Encrypted", fmt.Sprintf("%d", encryptedCount))
		}
		if unknownCount > 0 {
			printer.PrintKeyValue("  Unknown scheme", fmt.Sprintf("%d", unknownCount))
		}

		fmt.Println()

		// Resolver availability
		printer.PrintInfo("Resolver Availability")
		resolverTable := cli.NewTableData("Scheme", "Status", "Count")
		for _, scheme := range []string{"kms", "env", "autogen", "remote-kms", "encrypted"} {
			stats, exists := schemeStats[scheme]
			count := 0
			if exists {
				count = stats.count
			}

			status := "Available"
			if !isResolverAvailable(scheme) {
				status = "Not configured"
			}
			resolverTable.AddRow(scheme+"://", status, fmt.Sprintf("%d", count))
		}

		if err := printer.Print(*resolverTable); err != nil {
			return err
		}

		// Show secrets by path if requested
		if cmdFlags.showURIs && len(secrets) > 0 {
			fmt.Println()
			printer.PrintInfo("Secret Locations")
			secretTable := cli.NewTableData("Path", "Scheme", "URI (masked)")
			for _, secret := range secrets {
				scheme := detectScheme(secret.uri)
				secretTable.AddRow(secret.path, scheme, maskSecretURI(secret.uri))
			}
			if err := printer.Print(*secretTable); err != nil {
				return err
			}
		}

		// Warnings
		if unknownCount > 0 {
			fmt.Println()
			printer.PrintWarning(fmt.Sprintf("%d secret(s) with unknown scheme may not resolve correctly", unknownCount))
		}

		// Migration suggestion
		needsMigration := envCount + autoGenCount + remoteKMSCount + encryptedCount
		if needsMigration > 0 {
			fmt.Println()
			printer.PrintInfo(fmt.Sprintf("%d secret(s) could be migrated to local KMS for unified management", needsMigration))
			printer.PrintInfo("Run 'platformctl bootstrap secrets migrate' to migrate secrets")
		}
	}

	return nil
}

// detectScheme extracts the scheme from a secret URI
func detectScheme(uri string) string {
	for _, prefix := range []string{
		bootstrap.SchemeKMS,
		bootstrap.SchemeRemoteKMS,
		bootstrap.SchemeEnv,
		bootstrap.SchemeIDevID,
	} {
		if len(uri) >= len(prefix) && uri[:len(prefix)] == prefix {
			// Return scheme without ://
			return prefix[:len(prefix)-3]
		}
	}
	return "unknown"
}

// isResolverAvailable checks if a resolver is available for the given scheme
func isResolverAvailable(scheme string) bool {
	// In a real implementation, this would check the resolver registry
	// For now, assume common resolvers are available
	switch scheme {
	case "kms", "env":
		return true
	case "autogen", "remote-kms", "encrypted":
		// These require additional configuration
		return true
	default:
		return false
	}
}
