// SimpleLeaderChecker provides a simple LeaderChecker implementation
// that wraps a function for checking leadership.
type SimpleLeaderChecker struct {
	nodeID      string
	isLeaderFn  func() bool
	getLeaderFn func() string
}

// NewSimpleLeaderChecker creates a new SimpleLeaderChecker.
func NewSimpleLeaderChecker(
	nodeID string,
	isLeaderFn func() bool,
	getLeaderFn func() string,
) *SimpleLeaderChecker {
	return &SimpleLeaderChecker{
		nodeID:      nodeID,
		isLeaderFn:  isLeaderFn,
		getLeaderFn: getLeaderFn,
	}
}

// IsLeader returns whether this node is the leader.
func (c *SimpleLeaderChecker) IsLeader() bool {
	if c.isLeaderFn == nil {
		return false
	}
	return c.isLeaderFn()
}

// GetLeaderID returns the current leader ID.
func (c *SimpleLeaderChecker) GetLeaderID() string {
	if c.getLeaderFn == nil {
		return ""
	}
	return c.getLeaderFn()
}

// WaitForLeadership blocks until this node becomes leader.
func (c *SimpleLeaderChecker) WaitForLeadership(ctx context.Context) error {
	ticker := time.NewTicker(100 * time.Millisecond)
	defer ticker.Stop()

	for {
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-ticker.C:
			if c.IsLeader() {
				return nil
			}
		}
	}
}

