// Default CRL coordinator configuration values
const (
	DefaultCRLUpdateInterval     = 24 * time.Hour
	DefaultCRLGracePeriod        = 1 * time.Hour
	DefaultCRLHistoryRetention   = 7
	DefaultCRLSchedulerInterval  = 1 * time.Minute
	DefaultCRLOperationTimeout   = 5 * time.Minute
	DefaultCRLLeaderCheckRetries = 3
)

// CRLCoordinator provides cluster-wide CRL management with leader-based
// generation and QuicBaaS replication. Only the leader node generates CRLs,
// and all nodes can read the current CRL from the distributed store.
type CRLCoordinator interface {
	// Start initializes the coordinator and begins CRL update scheduling.
	Start(ctx context.Context) error

	// Stop gracefully stops the coordinator and its background tasks.
	Stop() error

	// RegenerateCRL triggers an immediate CRL regeneration.
	// Returns ErrNotLeader if this node is not the leader.
	RegenerateCRL() error

	// GetCurrentCRL retrieves the current CRL from the cluster store.
	GetCurrentCRL() (*CRL, error)

	// GetCRLStatus returns the current status of CRL coordination.
	GetCRLStatus() CRLStatus

	// IsResponsible returns true if this node should generate CRLs (is leader).
	IsResponsible() bool
}

// CRLStatus provides status information about CRL coordination.
type CRLStatus struct {
	// CurrentVersion is the version number of the current CRL.
	CurrentVersion uint64 `json:"current_version"`

	// LastUpdateTime is when the current CRL was generated.
	LastUpdateTime time.Time `json:"last_update_time"`

	// NextUpdateTime is when the next CRL update is scheduled.
	NextUpdateTime time.Time `json:"next_update_time"`

	// EntryCount is the number of revoked certificates in the current CRL.
	EntryCount int `json:"entry_count"`

	// IsLeader indicates if this node is the CRL generation leader.
	IsLeader bool `json:"is_leader"`

	// UpdatesGenerated is the total number of CRLs generated by this node.
	UpdatesGenerated int64 `json:"updates_generated"`

	// LastError contains the last error message if any.
	LastError string `json:"last_error,omitempty"`

	// GenerationDurationMs is the duration of the last CRL generation in ms.
	GenerationDurationMs int64 `json:"generation_duration_ms"`
}

// CRLUpdateHistory tracks a single CRL update event.
type CRLUpdateHistory struct {
	// Version is the CRL version number.
	Version uint64 `json:"version"`

	// GeneratedAt is when the CRL was generated.
	GeneratedAt time.Time `json:"generated_at"`

	// GeneratedBy is the node ID that generated the CRL.
	GeneratedBy string `json:"generated_by"`

	// EntryCount is the number of revoked certificates.
	EntryCount int `json:"entry_count"`

	// DurationMs is how long generation took in milliseconds.
	DurationMs int64 `json:"duration_ms"`

	// Success indicates if generation was successful.
	Success bool `json:"success"`

	// Error contains the error message if generation failed.
	Error string `json:"error,omitempty"`
}

// LeaderChecker provides an interface for checking leadership status.
// This abstraction allows the CRL coordinator to work with different
// cluster implementations.
type LeaderChecker interface {
	// IsLeader returns true if this node is the current cluster leader.
	IsLeader() bool

	// GetLeaderID returns the ID of the current leader node.
	GetLeaderID() string

	// WaitForLeadership blocks until this node becomes leader or context is cancelled.
	WaitForLeadership(ctx context.Context) error
}

// CRLGenerator provides an interface for generating CRL DER bytes.
// This abstraction separates CRL generation logic from coordination.
type CRLGenerator interface {
	// GenerateCRL creates a new CRL containing the provided revoked certificates.
	// Returns the DER-encoded CRL and any error.
	GenerateCRL(
		ctx context.Context,
		revokedCerts []*RevokedCertificate,
		issuer *x509.Certificate,
		issuerKey crypto.Signer,
		thisUpdate time.Time,
		nextUpdate time.Time,
	) ([]byte, error)

	// GetIssuerCertificate returns the CA certificate used to sign CRLs.
	GetIssuerCertificate() *x509.Certificate

	// GetIssuerKey returns the CA private key used to sign CRLs.
	GetIssuerKey() crypto.Signer
}

// CRLCoordinatorOption is a functional option for configuring the coordinator.
type CRLCoordinatorOption func(*crlCoordinatorConfig)

type crlCoordinatorConfig struct {
	updateInterval     time.Duration
	gracePeriod        time.Duration
	historyRetention   int
	schedulerInterval  time.Duration
	operationTimeout   time.Duration
	leaderCheckRetries int
}

// WithCRLUpdateInterval sets the interval between scheduled CRL updates.
func WithCRLUpdateInterval(d time.Duration) CRLCoordinatorOption {
	return func(c *crlCoordinatorConfig) {
		c.updateInterval = d
	}
}

// WithCRLGracePeriod sets the overlap period before NextUpdate.
func WithCRLGracePeriod(d time.Duration) CRLCoordinatorOption {
	return func(c *crlCoordinatorConfig) {
		c.gracePeriod = d
	}
}

// WithCRLHistoryRetention sets the number of historical CRL records to keep.
func WithCRLHistoryRetention(count int) CRLCoordinatorOption {
	return func(c *crlCoordinatorConfig) {
		c.historyRetention = count
	}
}

// WithCRLSchedulerInterval sets how often to check if CRL update is needed.
func WithCRLSchedulerInterval(d time.Duration) CRLCoordinatorOption {
	return func(c *crlCoordinatorConfig) {
		c.schedulerInterval = d
	}
}

// WithCRLOperationTimeout sets the timeout for CRL generation operations.
func WithCRLOperationTimeout(d time.Duration) CRLCoordinatorOption {
	return func(c *crlCoordinatorConfig) {
		c.operationTimeout = d
	}
}

// WithCRLLeaderCheckRetries sets the number of retries for leader checks.
func WithCRLLeaderCheckRetries(retries int) CRLCoordinatorOption {
	return func(c *crlCoordinatorConfig) {
		c.leaderCheckRetries = retries
	}
}

// crlCoordinator implements CRLCoordinator.
type crlCoordinator struct {
	config        *Config
	crlDAO        *CRLDAO
	certDAO       *CertificateDAO
	leaderChecker LeaderChecker
	generator     CRLGenerator
	logger        *logging.Logger

	// Configuration
	updateInterval     time.Duration
	gracePeriod        time.Duration
	historyRetention   int
	schedulerInterval  time.Duration
	operationTimeout   time.Duration
	leaderCheckRetries int

	// Lifecycle state using atomic operations for lock-free access
	running atomic.Bool
	stopped atomic.Bool

	// Status tracking with atomic operations
	status atomic.Value // stores *crlCoordinatorStatus

	// Update history with mutex protection for slice operations
	historyMu sync.RWMutex
	history   []*CRLUpdateHistory

	// Statistics
	updatesGenerated atomic.Int64
	lastError        atomic.Value // stores string

	// Goroutine coordination
	stopChan    chan struct{}
	stoppedChan chan struct{}

	// Manual regeneration trigger
	triggerChan chan struct{}
}

// crlCoordinatorStatus holds internal status atomically.
type crlCoordinatorStatus struct {
	currentVersion       uint64
	lastUpdateTime       time.Time
	nextUpdateTime       time.Time
	entryCount           int
	generationDurationMs int64
}

// NewCRLCoordinator creates a new CRL coordinator with the given dependencies.
func NewCRLCoordinator(
	config *Config,
	crlDAO *CRLDAO,
	certDAO *CertificateDAO,
	leaderChecker LeaderChecker,
	generator CRLGenerator,
	logger *logging.Logger,
	opts ...CRLCoordinatorOption,
) (CRLCoordinator, error) {
	if config == nil {
		return nil, ErrInvalidInput{Field: "config", Reason: "cannot be nil"}
	}
	if crlDAO == nil {
		return nil, ErrInvalidInput{Field: "crlDAO", Reason: "cannot be nil"}
	}
	if certDAO == nil {
		return nil, ErrInvalidInput{Field: "certDAO", Reason: "cannot be nil"}
	}
	if leaderChecker == nil {
		return nil, ErrInvalidInput{Field: "leaderChecker", Reason: "cannot be nil"}
	}
	if generator == nil {
		return nil, ErrInvalidInput{Field: "generator", Reason: "cannot be nil"}
	}
	if logger == nil {
		return nil, ErrInvalidInput{Field: "logger", Reason: "cannot be nil"}
	}

	cfg := &crlCoordinatorConfig{
		updateInterval:     DefaultCRLUpdateInterval,
		gracePeriod:        DefaultCRLGracePeriod,
		historyRetention:   DefaultCRLHistoryRetention,
		schedulerInterval:  DefaultCRLSchedulerInterval,
		operationTimeout:   DefaultCRLOperationTimeout,
		leaderCheckRetries: DefaultCRLLeaderCheckRetries,
	}
	for _, opt := range opts {
		opt(cfg)
	}

	c := &crlCoordinator{
		config:             config,
		crlDAO:             crlDAO,
		certDAO:            certDAO,
		leaderChecker:      leaderChecker,
		generator:          generator,
		logger:             logger,
		updateInterval:     cfg.updateInterval,
		gracePeriod:        cfg.gracePeriod,
		historyRetention:   cfg.historyRetention,
		schedulerInterval:  cfg.schedulerInterval,
		operationTimeout:   cfg.operationTimeout,
		leaderCheckRetries: cfg.leaderCheckRetries,
		history:            make([]*CRLUpdateHistory, 0, cfg.historyRetention),
		stopChan:           make(chan struct{}),
		stoppedChan:        make(chan struct{}),
		triggerChan:        make(chan struct{}, 1),
	}

	// Initialize status
	initialStatus := &crlCoordinatorStatus{
		lastUpdateTime: time.Time{},
		nextUpdateTime: time.Time{},
	}
	c.status.Store(initialStatus)
	c.lastError.Store("")

	return c, nil
}

// Start initializes the coordinator and begins the scheduler loop.
func (c *crlCoordinator) Start(ctx context.Context) error {
	if c.running.Swap(true) {
		return ErrCRLCoordinatorAlreadyRunning{}
	}

	if c.stopped.Load() {
		return ErrCRLCoordinatorStopped{}
	}

	c.logger.Info("CRL coordinator starting", "node_id", c.config.NodeID)

	// Load current CRL status from storage
	if err := c.loadInitialStatus(ctx); err != nil {
		c.logger.Warn("failed to load initial CRL status", "error", err)
		// Continue anyway - we'll generate a new CRL if needed
	}

	// Start the scheduler goroutine
	go c.schedulerLoop()

	c.logger.Info("CRL coordinator started successfully", "node_id", c.config.NodeID)

	return nil
}

// Stop gracefully stops the coordinator.
func (c *crlCoordinator) Stop() error {
	if !c.running.Load() {
		return ErrCRLCoordinatorNotRunning{}
	}

	c.logger.Info("CRL coordinator stopping", "node_id", c.config.NodeID)

	// Signal scheduler to stop
	close(c.stopChan)

	// Wait for scheduler to finish
	select {
	case <-c.stoppedChan:
		// Scheduler stopped cleanly
	case <-time.After(30 * time.Second):
		c.logger.Warn("CRL coordinator scheduler shutdown timed out")
	}

	c.running.Store(false)
	c.stopped.Store(true)

	c.logger.Info("CRL coordinator stopped", "node_id", c.config.NodeID)

	return nil
}

// RegenerateCRL triggers an immediate CRL regeneration.
func (c *crlCoordinator) RegenerateCRL() error {
	if !c.running.Load() {
		return ErrCRLCoordinatorNotRunning{}
	}

	if !c.leaderChecker.IsLeader() {
		return ErrNotLeader{NodeID: c.config.NodeID, LeaderID: c.leaderChecker.GetLeaderID()}
	}

	// Send trigger signal (non-blocking)
	select {
	case c.triggerChan <- struct{}{}:
		// Trigger sent
	default:
		// Trigger already pending
	}

	return nil
}

// GetCurrentCRL retrieves the current CRL from storage.
func (c *crlCoordinator) GetCurrentCRL() (*CRL, error) {
	ctx, cancel := context.WithTimeout(context.Background(), DefaultRequestTimeout)
	defer cancel()

	crl, err := c.crlDAO.GetCurrent(ctx, c.config.TenantID)
	if err != nil {
		return nil, err
	}

	return crl, nil
}

// GetCRLStatus returns the current CRL coordination status.
func (c *crlCoordinator) GetCRLStatus() CRLStatus {
	status := c.loadStatus()

	lastErr := ""
	if v := c.lastError.Load(); v != nil {
		lastErr = v.(string)
	}

	return CRLStatus{
		CurrentVersion:       status.currentVersion,
		LastUpdateTime:       status.lastUpdateTime,
		NextUpdateTime:       status.nextUpdateTime,
		EntryCount:           status.entryCount,
		IsLeader:             c.leaderChecker.IsLeader(),
		UpdatesGenerated:     c.updatesGenerated.Load(),
		LastError:            lastErr,
		GenerationDurationMs: status.generationDurationMs,
	}
}

// IsResponsible returns true if this node is the leader.
func (c *crlCoordinator) IsResponsible() bool {
	return c.leaderChecker.IsLeader()
}

// GetHistory returns the CRL update history.
func (c *crlCoordinator) GetHistory() []*CRLUpdateHistory {
	c.historyMu.RLock()
	defer c.historyMu.RUnlock()

	result := make([]*CRLUpdateHistory, len(c.history))
	copy(result, c.history)
	return result
}

// loadInitialStatus loads the current CRL from storage and updates internal status.
func (c *crlCoordinator) loadInitialStatus(ctx context.Context) error {
	crl, err := c.crlDAO.GetCurrent(ctx, c.config.TenantID)
	if err != nil {
		// If no CRL exists, that's okay - we'll generate one
		if _, ok := err.(ErrCRLNotFound); ok {
			return nil
		}
		return err
	}

	c.updateStatus(func(s *crlCoordinatorStatus) {
		s.currentVersion = crl.Version
		s.lastUpdateTime = crl.ThisUpdate
		s.nextUpdateTime = crl.NextUpdate
		s.entryCount = len(crl.RevokedCertificates)
	})

	return nil
}

// schedulerLoop runs the CRL update scheduler.
func (c *crlCoordinator) schedulerLoop() {
	defer close(c.stoppedChan)

	ticker := time.NewTicker(c.schedulerInterval)
	defer ticker.Stop()

	c.logger.Debug("CRL scheduler loop started", "interval", c.schedulerInterval)

	for {
		select {
		case <-c.stopChan:
			c.logger.Debug("CRL scheduler loop stopping")
			return

		case <-ticker.C:
			c.checkAndUpdateCRL()

		case <-c.triggerChan:
			c.logger.Debug("CRL regeneration triggered manually")
			c.performCRLUpdate()
		}
	}
}

// checkAndUpdateCRL checks if a CRL update is needed and performs it.
func (c *crlCoordinator) checkAndUpdateCRL() {
	// Only leader generates CRLs
	if !c.leaderChecker.IsLeader() {
		return
	}

	status := c.loadStatus()
	now := time.Now().UTC()

	// Check if update is needed
	needsUpdate := false

	// Case 1: No CRL exists yet
	if status.lastUpdateTime.IsZero() {
		needsUpdate = true
		c.logger.Debug("CRL update needed: no existing CRL")
	}

	// Case 2: CRL is approaching expiration (within grace period)
	if !needsUpdate && !status.nextUpdateTime.IsZero() {
		expirationThreshold := status.nextUpdateTime.Add(-c.gracePeriod)
		if now.After(expirationThreshold) {
			needsUpdate = true
			c.logger.Debug("CRL update needed: approaching expiration",
				"next_update", status.nextUpdateTime,
				"threshold", expirationThreshold)
		}
	}

	// Case 3: Scheduled update interval has passed
	if !needsUpdate && !status.lastUpdateTime.IsZero() {
		nextScheduledUpdate := status.lastUpdateTime.Add(c.updateInterval)
		if now.After(nextScheduledUpdate) {
			needsUpdate = true
			c.logger.Debug("CRL update needed: scheduled interval elapsed",
				"last_update", status.lastUpdateTime,
				"interval", c.updateInterval)
		}
	}

	if needsUpdate {
		c.performCRLUpdate()
	}
}

// performCRLUpdate generates and stores a new CRL.
func (c *crlCoordinator) performCRLUpdate() {
	// Double-check leadership before generating
	if !c.leaderChecker.IsLeader() {
		c.logger.Debug("skipping CRL update: not leader")
		return
	}

	ctx, cancel := context.WithTimeout(context.Background(), c.operationTimeout)
	defer cancel()

	startTime := time.Now()
	c.logger.Info("starting CRL generation", "node_id", c.config.NodeID)

	// Get all revoked certificates
	revokedCerts, err := c.getRevokedCertificates(ctx)
	if err != nil {
		c.recordUpdateFailure(startTime, err)
		return
	}

	// Generate timestamps
	thisUpdate := time.Now().UTC()
	nextUpdate := thisUpdate.Add(c.updateInterval).Add(c.gracePeriod)

	// Generate the CRL
	issuerCert := c.generator.GetIssuerCertificate()
	issuerKey := c.generator.GetIssuerKey()

	der, err := c.generator.GenerateCRL(ctx, revokedCerts, issuerCert, issuerKey, thisUpdate, nextUpdate)
	if err != nil {
		c.recordUpdateFailure(startTime, err)
		return
	}

	// Create CRL entity
	crl := NewCRL(
		CurrentCRLID,
		der,
		issuerCert.Subject.String(),
		thisUpdate,
		nextUpdate,
		c.config.TenantID,
	)
	crl.RevokedCertificates = revokedCerts

	// Store the CRL
	if err := c.crlDAO.SaveCurrent(ctx, crl); err != nil {
		c.recordUpdateFailure(startTime, err)
		return
	}

	// Record success
	c.recordUpdateSuccess(startTime, crl)
}

// getRevokedCertificates retrieves all revoked certificates from storage.
func (c *crlCoordinator) getRevokedCertificates(ctx context.Context) ([]*RevokedCertificate, error) {
	// List all certificates and filter for revoked ones
	var allRevoked []*RevokedCertificate
	pageToken := ""

	for {
		certs, nextToken, err := c.certDAO.List(ctx, c.config.TenantID, 1000, pageToken)
		if err != nil {
			return nil, ErrOperationFailed{Operation: "list certificates for CRL", Cause: err}
		}

		for _, cert := range certs {
			if cert.IsRevoked() && !cert.IsExpired() {
				allRevoked = append(allRevoked, &RevokedCertificate{
					SerialNumber:     new(big.Int).Set(cert.SerialNumber),
					RevocationTime:   *cert.RevokedAt,
					RevocationReason: cert.RevocationReason,
				})
			}
		}

		if nextToken == "" {
			break
		}
		pageToken = nextToken
	}

	return allRevoked, nil
}

// recordUpdateSuccess records a successful CRL update.
func (c *crlCoordinator) recordUpdateSuccess(startTime time.Time, crl *CRL) {
	duration := time.Since(startTime)

	c.updateStatus(func(s *crlCoordinatorStatus) {
		s.currentVersion = crl.Version
		s.lastUpdateTime = crl.ThisUpdate
		s.nextUpdateTime = crl.NextUpdate
		s.entryCount = len(crl.RevokedCertificates)
		s.generationDurationMs = duration.Milliseconds()
	})

	c.updatesGenerated.Add(1)
	c.lastError.Store("")

	// Add to history
	c.addHistory(&CRLUpdateHistory{
		Version:     crl.Version,
		GeneratedAt: crl.ThisUpdate,
		GeneratedBy: c.config.NodeID,
		EntryCount:  len(crl.RevokedCertificates),
		DurationMs:  duration.Milliseconds(),
		Success:     true,
	})

	c.logger.Info("CRL generation completed successfully",
		"version", crl.Version,
		"entry_count", len(crl.RevokedCertificates),
		"duration_ms", duration.Milliseconds(),
		"next_update", crl.NextUpdate)
}

// recordUpdateFailure records a failed CRL update.
func (c *crlCoordinator) recordUpdateFailure(startTime time.Time, err error) {
	duration := time.Since(startTime)

	c.lastError.Store(err.Error())

	// Add to history
	c.addHistory(&CRLUpdateHistory{
		GeneratedAt: time.Now().UTC(),
		GeneratedBy: c.config.NodeID,
		DurationMs:  duration.Milliseconds(),
		Success:     false,
		Error:       err.Error(),
	})

	c.logger.Error(err,
		"duration_ms", duration.Milliseconds())
}

// addHistory adds an entry to the update history with retention enforcement.
func (c *crlCoordinator) addHistory(entry *CRLUpdateHistory) {
	c.historyMu.Lock()
	defer c.historyMu.Unlock()

	c.history = append(c.history, entry)

	// Enforce retention limit
	if len(c.history) > c.historyRetention {
		c.history = c.history[len(c.history)-c.historyRetention:]
	}
}

// loadStatus returns the current status atomically.
func (c *crlCoordinator) loadStatus() *crlCoordinatorStatus {
	val := c.status.Load()
	if val == nil {
		return &crlCoordinatorStatus{}
	}
	return val.(*crlCoordinatorStatus)
}

// updateStatus atomically updates the coordinator status.
func (c *crlCoordinator) updateStatus(fn func(*crlCoordinatorStatus)) {
	for {
		current := c.loadStatus()
		newStatus := *current
		fn(&newStatus)

		// Use CompareAndSwap for true lock-free update
		if c.status.CompareAndSwap(current, &newStatus) {
			return
		}
		// Retry on conflict
	}
}

