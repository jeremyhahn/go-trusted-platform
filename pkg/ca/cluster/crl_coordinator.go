// DefaultCRLGenerator provides a standard CRL generation implementation
// using the Go standard library.
type DefaultCRLGenerator struct {
	issuerCert *x509.Certificate
	issuerKey  crypto.Signer
	crlNumber  atomic.Uint64
}

// NewDefaultCRLGenerator creates a new DefaultCRLGenerator.
func NewDefaultCRLGenerator(issuerCert *x509.Certificate, issuerKey crypto.Signer) (*DefaultCRLGenerator, error) {
	if issuerCert == nil {
		return nil, ErrInvalidInput{Field: "issuerCert", Reason: "cannot be nil"}
	}
	if issuerKey == nil {
		return nil, ErrInvalidInput{Field: "issuerKey", Reason: "cannot be nil"}
	}

	return &DefaultCRLGenerator{
		issuerCert: issuerCert,
		issuerKey:  issuerKey,
	}, nil
}

// GenerateCRL creates a DER-encoded CRL.
func (g *DefaultCRLGenerator) GenerateCRL(
	ctx context.Context,
	revokedCerts []*RevokedCertificate,
	issuer *x509.Certificate,
	issuerKey crypto.Signer,
	thisUpdate time.Time,
	nextUpdate time.Time,
) ([]byte, error) {
	// Convert revoked certificates to pkix format
	revokedList := make([]pkix.RevokedCertificate, len(revokedCerts))
	for i, rc := range revokedCerts {
		revokedList[i] = pkix.RevokedCertificate{
			SerialNumber:   rc.SerialNumber,
			RevocationTime: rc.RevocationTime,
		}
	}

	// Increment CRL number
	crlNumber := g.crlNumber.Add(1)

	// Create CRL template
	crlTemplate := &x509.RevocationList{
		RevokedCertificates: revokedList,
		Number:              big.NewInt(int64(crlNumber)),
		ThisUpdate:          thisUpdate,
		NextUpdate:          nextUpdate,
	}

	// Generate CRL
	crlDER, err := x509.CreateRevocationList(nil, crlTemplate, issuer, issuerKey)
	if err != nil {
		return nil, ErrCRLGenerationFailed{Reason: "failed to create revocation list", Cause: err}
	}

	return crlDER, nil
}

// GetIssuerCertificate returns the CA certificate.
func (g *DefaultCRLGenerator) GetIssuerCertificate() *x509.Certificate {
	return g.issuerCert
}

// GetIssuerKey returns the CA private key.
func (g *DefaultCRLGenerator) GetIssuerKey() crypto.Signer {
	return g.issuerKey
}

