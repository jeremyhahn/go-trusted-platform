// Module-signing key defaults. The kernel build (certs/Makefile) embeds the
// certificate from CONFIG_MODULE_SIG_KEY into .builtin_trusted_keys, so the
// key must be a single PEM file containing the private key followed by its
// self-signed certificate — exactly the layout the kernel's autogenerated
// certs/signing_key.pem uses.
const (
	// DefaultModuleKeyBits matches the kernel's own x509.genkey default.
	DefaultModuleKeyBits = 4096

	// MinModuleKeyBits is the platform-wide RSA floor.
	MinModuleKeyBits = 2048

	// DefaultModuleKeyValidYears is the certificate validity applied when
	// ModuleSigningKeyConfig.ValidYears is zero.
	DefaultModuleKeyValidYears = 10

	// DefaultModuleKeyCN is the certificate CommonName applied when
	// ModuleSigningKeyConfig.CommonName is empty.
	DefaultModuleKeyCN = "Trusted Platform Module Signing Key"

	pemTypePrivateKey  = "PRIVATE KEY"
	pemTypeCertificate = "CERTIFICATE"
)

// ErrModuleKeyExists indicates the target module-signing key file already
// exists and Force was not set. The stable key must never be silently
// regenerated: a new key invalidates every previously built kernel's trust in
// out-of-tree modules signed with the old key.
type ErrModuleKeyExists struct {
	Path string
}

// Error implements the error interface.
func (e ErrModuleKeyExists) Error() string {
	return "secureboot: module-signing key already exists (use Force to overwrite): " + e.Path
}

// ErrModuleKeyNotFound indicates the module-signing key file does not exist.
type ErrModuleKeyNotFound struct {
	Path string
	Err  error
}

// Error implements the error interface.
func (e ErrModuleKeyNotFound) Error() string {
	return "secureboot: module-signing key not found: " + e.Path + ": " + e.Err.Error()
}

// Unwrap returns the underlying cause.
func (e ErrModuleKeyNotFound) Unwrap() error { return e.Err }

// ErrModuleKeyMalformed indicates the module-signing key file could not be
// parsed as the expected key+certificate PEM bundle.
type ErrModuleKeyMalformed struct {
	Path   string
	Reason string
}

// Error implements the error interface.
func (e ErrModuleKeyMalformed) Error() string {
	return "secureboot: malformed module-signing key " + e.Path + ": " + e.Reason
}

// ModuleSigningKeyConfig configures GenerateModuleSigningKey.
type ModuleSigningKeyConfig struct {
	// Path is the output file for the combined key+certificate PEM bundle
	// consumed by the FIPS kernel build via CONFIG_MODULE_SIG_KEY. Required.
	Path string

	// KeyBits is the RSA modulus size. Defaults to DefaultModuleKeyBits;
	// values below MinModuleKeyBits are rejected.
	KeyBits int

	// CommonName is the certificate CN. Defaults to DefaultModuleKeyCN.
	CommonName string

	// Organization is the optional certificate Organization.
	Organization string

	// Country is the optional certificate Country.
	Country string

	// ValidYears is the certificate validity. Defaults to
	// DefaultModuleKeyValidYears.
	ValidYears int

	// Force overwrites an existing key file. Default false: regenerating the
	// stable key orphans every module signed with the previous key.
	Force bool
}

// ModuleSigningKey is a loaded (or freshly generated) module-signing keypair.
type ModuleSigningKey struct {
	// Path is the PEM bundle location on disk.
	Path string

	// Signer signs module digests (RSA PKCS#1 v1.5, the kernel's
	// CONFIG_MODULE_SIG_SHA256 scheme).
	Signer crypto.Signer

	// Certificate is the self-signed certificate embedded in the kernel's
	// builtin trusted keyring at build time.
	Certificate *x509.Certificate
}

// GenerateModuleSigningKey generates the stable platform module-signing key
// used by the FIPS kernel build (CONFIG_MODULE_SIG_KEY) and by pkg/modulesign
// for out-of-tree module signing. It writes a single PEM bundle — PKCS#8
// private key followed by a self-signed certificate — matching the layout of
// the kernel's autogenerated certs/signing_key.pem, with 0600 permissions.
//
// The certificate carries the extensions the kernel's x509 parser expects
// (basicConstraints CA:FALSE, keyUsage digitalSignature, subject and
// authority key identifiers). An existing key file is never overwritten
// unless cfg.Force is set; see ErrModuleKeyExists.
func GenerateModuleSigningKey(ctx context.Context, cfg *ModuleSigningKeyConfig) (*ModuleSigningKey, error) {
	if cfg == nil {
		return nil, ErrConfigNil
	}
	if cfg.Path == "" {
		return nil, &SentinelCauseError{Sentinel: ErrInvalidConfig, Cause: &MessageError{Msg: "Path cannot be empty"}}
	}

	bits := cfg.KeyBits
	if bits == 0 {
		bits = DefaultModuleKeyBits
	}
	if bits < MinModuleKeyBits {
		return nil, &SentinelCauseError{Sentinel: ErrInvalidConfig, Cause: &MessageError{Msg: "KeyBits must be at least 2048"}}
	}

	validYears := cfg.ValidYears
	if validYears == 0 {
		validYears = DefaultModuleKeyValidYears
	}

	commonName := cfg.CommonName
	if commonName == "" {
		commonName = DefaultModuleKeyCN
	}

	if !cfg.Force {
		if _, err := os.Stat(cfg.Path); err == nil {
			return nil, ErrModuleKeyExists{Path: cfg.Path}
		}
	}

	select {
	case <-ctx.Done():
		return nil, ctx.Err()
	default:
	}

	key, err := rsa.GenerateKey(rand.Reader, bits)
	if err != nil {
		return nil, &SentinelCauseError{Sentinel: ErrKeyGenFailed, Cause: err}
	}

	cert, err := buildModuleSigningCert(key, commonName, cfg.Organization, cfg.Country, validYears)
	if err != nil {
		return nil, err
	}

	if err := writeModuleSigningBundle(cfg.Path, key, cert); err != nil {
		return nil, err
	}

	return &ModuleSigningKey{Path: cfg.Path, Signer: key, Certificate: cert}, nil
}

// LoadModuleSigningKey loads a module-signing key bundle previously written by
// GenerateModuleSigningKey (or the kernel's own certs/signing_key.pem layout):
// a PEM private key block followed by a PEM certificate block in one file.
func LoadModuleSigningKey(path string) (*ModuleSigningKey, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, ErrModuleKeyNotFound{Path: path, Err: err}
	}

	var signer crypto.Signer
	var cert *x509.Certificate

	rest := data
	for {
		var block *pem.Block
		block, rest = pem.Decode(rest)
		if block == nil {
			break
		}
		switch block.Type {
		case pemTypePrivateKey:
			parsed, parseErr := x509.ParsePKCS8PrivateKey(block.Bytes)
			if parseErr != nil {
				return nil, ErrModuleKeyMalformed{Path: path, Reason: "invalid PKCS#8 private key: " + parseErr.Error()}
			}
			s, ok := parsed.(crypto.Signer)
			if !ok {
				return nil, ErrModuleKeyMalformed{Path: path, Reason: "private key does not implement crypto.Signer"}
			}
			signer = s
		case "RSA PRIVATE KEY":
			parsed, parseErr := x509.ParsePKCS1PrivateKey(block.Bytes)
			if parseErr != nil {
				return nil, ErrModuleKeyMalformed{Path: path, Reason: "invalid PKCS#1 private key: " + parseErr.Error()}
			}
			signer = parsed
		case pemTypeCertificate:
			parsed, parseErr := x509.ParseCertificate(block.Bytes)
			if parseErr != nil {
				return nil, ErrModuleKeyMalformed{Path: path, Reason: "invalid certificate: " + parseErr.Error()}
			}
			cert = parsed
		}
	}

	if signer == nil {
		return nil, ErrModuleKeyMalformed{Path: path, Reason: "no private key PEM block found"}
	}
	if cert == nil {
		return nil, ErrModuleKeyMalformed{Path: path, Reason: "no certificate PEM block found"}
	}

	return &ModuleSigningKey{Path: path, Signer: signer, Certificate: cert}, nil
}

// buildModuleSigningCert self-signs the module-signing certificate with the
// extensions the kernel keyring loader expects.
func buildModuleSigningCert(key *rsa.PrivateKey, cn, org, country string, validYears int) (*x509.Certificate, error) {
	serialNumber, err := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 128))
	if err != nil {
		return nil, &SentinelCauseError{Sentinel: ErrKeyGenFailed, Cause: err}
	}

	subject := pkix.Name{CommonName: cn}
	if org != "" {
		subject.Organization = []string{org}
	}
	if country != "" {
		subject.Country = []string{country}
	}

	// Subject/authority key identifiers mirror the kernel's x509.genkey
	// (subjectKeyIdentifier=hash, authorityKeyIdentifier=keyid). Go only
	// auto-computes SKID for CA certificates, so compute it explicitly.
	spki, err := x509.MarshalPKIXPublicKey(&key.PublicKey)
	if err != nil {
		return nil, &SentinelCauseError{Sentinel: ErrKeyGenFailed, Cause: err}
	}
	skid := sha1.Sum(spki)

	template := &x509.Certificate{
		SerialNumber:          serialNumber,
		Subject:               subject,
		NotBefore:             time.Now(),
		NotAfter:              time.Now().AddDate(validYears, 0, 0),
		KeyUsage:              x509.KeyUsageDigitalSignature,
		BasicConstraintsValid: true,
		IsCA:                  false,
		SubjectKeyId:          skid[:],
		AuthorityKeyId:        skid[:],
	}

	certDER, err := x509.CreateCertificate(rand.Reader, template, template, &key.PublicKey, key)
	if err != nil {
		return nil, &SentinelCauseError{Sentinel: ErrKeyGenFailed, Cause: err}
	}

	return x509.ParseCertificate(certDER)
}

// writeModuleSigningBundle writes the PKCS#8 key + certificate PEM bundle with
// owner-only permissions.
func writeModuleSigningBundle(path string, key *rsa.PrivateKey, cert *x509.Certificate) error {
	if dir := filepath.Dir(path); dir != "." {
		if err := os.MkdirAll(dir, 0700); err != nil {
			return &SentinelCauseError{Sentinel: ErrWriteFailed, Cause: err}
		}
	}

	keyDER, err := x509.MarshalPKCS8PrivateKey(key)
	if err != nil {
		return &SentinelCauseError{Sentinel: ErrWriteFailed, Cause: err}
	}

	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0600)
	if err != nil {
		return &SentinelCauseError{Sentinel: ErrWriteFailed, Cause: err}
	}
	defer f.Close()

	if err := pem.Encode(f, &pem.Block{Type: pemTypePrivateKey, Bytes: keyDER}); err != nil {
		return &SentinelCauseError{Sentinel: ErrWriteFailed, Cause: err}
	}
	if err := pem.Encode(f, &pem.Block{Type: pemTypeCertificate, Bytes: cert.Raw}); err != nil {
		return &SentinelCauseError{Sentinel: ErrWriteFailed, Cause: err}
	}
	return nil
}
