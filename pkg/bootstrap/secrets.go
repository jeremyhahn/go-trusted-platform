// Package bootstrap provides secret resolution and migration during platform bootstrap.
// It handles resolving secrets from various sources (environment, remote KMS, auto-generation)
// and migrating them to the local KMS for unified access.
package bootstrap

import (
	"context"
	"fmt"
	"log/slog"
	"reflect"
	"strings"
)

// URI scheme prefixes for secret resolution.
const (
	SchemeKMS       = "kms://"
	SchemeRemoteKMS = "remote-kms://"
	SchemeAutoGen   = "autogen://"
	SchemeEnv       = "env://"
	SchemeEncrypted = "encrypted://"
	SchemeDynamic   = "dynamic://"
	SchemeXKMS      = "xkms://"
)

// Strategy constants for tracking how secrets were resolved.
const (
	StrategyKMS       = "kms"
	StrategyRemoteKMS = "remote-kms"
	StrategyAutoGen   = "autogen"
	StrategyEnv       = "env"
	StrategyEncrypted = "encrypted"
	StrategyDynamic   = "dynamic"
	StrategyXKMS      = "xkms"
	StrategyLiteral   = "literal"
	StrategyPlainText = "plaintext"
)

// SecretStructTag is the struct tag key used to mark fields as secrets.
const SecretStructTag = "secret"

// SecretsClient provides an interface for storing and retrieving secrets.
// This abstraction allows the SecretManager to work with various KMS backends.
type SecretsClient interface {
	// StoreSecret stores a secret at the specified path with optional metadata.
	StoreSecret(ctx context.Context, path string, data []byte, metadata map[string]string) error

	// GetSecret retrieves a secret from the specified path.
	GetSecret(ctx context.Context, path string) ([]byte, error)
}

// SecretResolver resolves secret URIs to their plaintext values.
// Implementations handle different URI schemes (kms://, remote-kms://, autogen://, etc.).
type SecretResolver interface {
	// Scheme returns the URI scheme this resolver handles (e.g., "kms://").
	Scheme() string

	// Resolve resolves the URI to its plaintext secret value.
	Resolve(ctx context.Context, uri string) ([]byte, error)

	// CanResolve returns true if this resolver can handle the given URI.
	CanResolve(uri string) bool
}

// ResolverRegistry manages multiple secret resolvers and routes resolution
// requests to the appropriate resolver based on URI scheme.
type ResolverRegistry struct {
	resolvers map[string]SecretResolver
	logger    *slog.Logger
}

// NewResolverRegistry creates a new resolver registry.
func NewResolverRegistry(logger *slog.Logger) *ResolverRegistry {
	return &ResolverRegistry{
		resolvers: make(map[string]SecretResolver),
		logger:    logger,
	}
}

// Register adds a resolver to the registry.
func (r *ResolverRegistry) Register(resolver SecretResolver) {
	r.resolvers[resolver.Scheme()] = resolver
	r.logger.Debug("registered secret resolver", "scheme", resolver.Scheme())
}

// Resolve routes the URI to the appropriate resolver.
func (r *ResolverRegistry) Resolve(ctx context.Context, uri string) ([]byte, error) {
	for scheme, resolver := range r.resolvers {
		if resolver.CanResolve(uri) {
			r.logger.Debug("resolving secret", "scheme", scheme, "uri", maskURI(uri))
			return resolver.Resolve(ctx, uri)
		}
	}
	return nil, ErrNoResolverForURI{URI: maskURI(uri)}
}

// CanResolve returns true if any registered resolver can handle the URI.
func (r *ResolverRegistry) CanResolve(uri string) bool {
	for _, resolver := range r.resolvers {
		if resolver.CanResolve(uri) {
			return true
		}
	}
	return false
}

// MigratedSecret contains information about a secret that was resolved
// and migrated to the local KMS.
type MigratedSecret struct {
	// ConfigPath is the dot-notation path in the config struct (e.g., "kms.backends.tpm2.srk-auth").
	ConfigPath string

	// KMSPath is the local KMS path where the secret is stored (e.g., "kms://config/kms/backends/tpm2/srk-auth").
	KMSPath string

	// Strategy indicates how the secret was originally provided (encrypted, remote-kms, autogen, plaintext, etc.).
	Strategy string

	// OriginalURI is the original URI before migration.
	OriginalURI string
}

// MigrationResult contains the results of processing secrets in a configuration.
type MigrationResult struct {
	// Migrated contains all secrets that were resolved and migrated to local KMS.
	Migrated []MigratedSecret

	// AutoGenerated contains config paths of secrets that were auto-generated.
	AutoGenerated []string

	// Errors contains any non-fatal errors encountered during migration.
	Errors []error
}

// HasErrors returns true if any errors occurred during migration.
func (r *MigrationResult) HasErrors() bool {
	return len(r.Errors) > 0
}

// ErrorCount returns the number of errors encountered.
func (r *MigrationResult) ErrorCount() int {
	return len(r.Errors)
}

// MigratedCount returns the number of successfully migrated secrets.
func (r *MigrationResult) MigratedCount() int {
	return len(r.Migrated)
}

// AutoGeneratedCount returns the number of auto-generated secrets.
func (r *MigrationResult) AutoGeneratedCount() int {
	return len(r.AutoGenerated)
}

// SecretManager handles secret resolution and migration during platform bootstrap.
// It walks configuration structs, resolves secret URIs, and migrates them to local KMS.
type SecretManager struct {
	registry   *ResolverRegistry
	localKMS   SecretsClient
	configPath string
	logger     *slog.Logger
}

// NewSecretManager creates a new SecretManager.
//
// Parameters:
//   - registry: The resolver registry containing registered secret resolvers
//   - kms: The local KMS client for storing resolved secrets
//   - configPath: Base path prefix for KMS storage (e.g., "config")
//   - logger: Logger for debug and error messages
func NewSecretManager(registry *ResolverRegistry, kms SecretsClient, configPath string, logger *slog.Logger) (*SecretManager, error) {
	if registry == nil {
		return nil, ErrNilRegistry{}
	}
	if kms == nil {
		return nil, ErrNilKMSClient{}
	}
	if logger == nil {
		return nil, ErrNilLogger{}
	}
	return &SecretManager{
		registry:   registry,
		localKMS:   kms,
		configPath: configPath,
		logger:     logger,
	}, nil
}

// ProcessConfig walks the configuration struct, resolves all secret URIs,
// stores them in the local KMS, and returns migration results.
//
// The function uses reflection to find string fields that contain secret URIs
// (identified by URI scheme prefixes). For each secret found:
//  1. Resolves the URI using the appropriate resolver
//  2. Stores the resolved value in local KMS
//  3. Tracks the migration for config file updates
//
// Fields are identified by their struct tag "secret" or by URI prefix detection.
func (m *SecretManager) ProcessConfig(ctx context.Context, cfg interface{}) (*MigrationResult, error) {
	if cfg == nil {
		return nil, ErrNilConfig{}
	}

	result := &MigrationResult{
		Migrated:      make([]MigratedSecret, 0),
		AutoGenerated: make([]string, 0),
		Errors:        make([]error, 0),
	}

	val := reflect.ValueOf(cfg)
	if val.Kind() == reflect.Ptr {
		val = val.Elem()
	}

	if val.Kind() != reflect.Struct {
		return nil, ErrInvalidConfigType{Kind: val.Kind().String()}
	}

	m.logger.Debug("processing config for secrets", "type", val.Type().Name())

	err := m.walkStruct(ctx, val, "", result)
	if err != nil {
		return result, err
	}

	return result, nil
}

// migratePlainTextToKMS stores a plain-text secret value in the KMS and returns
// the kms:// URI that replaces it. The KMS path is derived from the field's
// dot-notation config path, converted to slash-separated segments.
func (m *SecretManager) migratePlainTextToKMS(ctx context.Context, fieldPath, plainText string) (string, error) {
	kmsPath := m.buildKMSPath(fieldPath)

	metadata := map[string]string{
		"source":      "plaintext-migration",
		"config_path": fieldPath,
	}

	err := m.localKMS.StoreSecret(ctx, kmsPath, []byte(plainText), metadata)
	if err != nil {
		return "", err
	}

	return SchemeKMS + kmsPath, nil
}

// walkStruct recursively walks a struct and processes secret fields.
// It handles both URI-based secrets and plain-text secrets tagged with secret:"true".
func (m *SecretManager) walkStruct(ctx context.Context, val reflect.Value, path string, result *MigrationResult) error {
	typ := val.Type()

	for i := 0; i < val.NumField(); i++ {
		field := val.Field(i)
		fieldType := typ.Field(i)

		// Skip unexported fields
		if !field.CanSet() {
			continue
		}

		// Build the config path
		fieldPath := buildFieldPath(path, fieldType)

		switch field.Kind() {
		case reflect.String:
			isSecretField := fieldType.Tag.Get(SecretStructTag) == "true"
			if err := m.processStringField(ctx, field, fieldType, fieldPath, isSecretField, result); err != nil {
				result.Errors = append(result.Errors, ErrFieldProcessing{
					Path:  fieldPath,
					Cause: err,
				})
			}

		case reflect.Ptr:
			if !field.IsNil() && field.Elem().Kind() == reflect.Struct {
				if err := m.walkStruct(ctx, field.Elem(), fieldPath, result); err != nil {
					return err
				}
			}

		case reflect.Struct:
			if err := m.walkStruct(ctx, field, fieldPath, result); err != nil {
				return err
			}

		case reflect.Slice:
			if err := m.processSlice(ctx, field, fieldPath, result); err != nil {
				return err
			}

		case reflect.Map:
			if err := m.processMap(ctx, field, fieldPath, result); err != nil {
				return err
			}
		}
	}

	return nil
}

// processStringField handles a string field that may contain a secret URI or
// a plain-text secret identified by the secret:"true" struct tag.
func (m *SecretManager) processStringField(ctx context.Context, field reflect.Value, fieldType reflect.StructField, path string, isSecretField bool, result *MigrationResult) error {
	value := field.String()
	if value == "" {
		return nil
	}

	// If the value is already a secret URI, resolve and migrate it
	if m.isSecretURI(value) {
		return m.resolveAndMigrateURI(ctx, field, path, value, result)
	}

	// If the field is tagged secret:"true" but contains plain text,
	// migrate the plain-text value to the KMS
	if isSecretField {
		kmsURI, err := m.migratePlainTextToKMS(ctx, path, value)
		if err != nil {
			return ErrPlainTextSecretMigration{
				Path:  path,
				Cause: err,
			}
		}

		field.SetString(kmsURI)

		result.Migrated = append(result.Migrated, MigratedSecret{
			ConfigPath:  path,
			KMSPath:     kmsURI,
			Strategy:    StrategyPlainText,
			OriginalURI: "***",
		})

		m.logger.Info("migrated plain-text secret to local KMS",
			"config_path", path,
			"kms_path", kmsURI,
			"strategy", StrategyPlainText,
		)
	}

	return nil
}

// resolveAndMigrateURI resolves a secret URI and migrates the result to the local KMS.
func (m *SecretManager) resolveAndMigrateURI(ctx context.Context, field reflect.Value, path, uri string, result *MigrationResult) error {
	strategy := m.detectStrategy(uri)
	m.logger.Debug("found secret field", "path", path, "strategy", strategy)

	// Resolve the secret
	secretValue, err := m.registry.Resolve(ctx, uri)
	if err != nil {
		return ErrSecretResolution{
			URI:   maskURI(uri),
			Cause: err,
		}
	}

	// Migrate to local KMS
	kmsPath, err := m.migrateToKMS(ctx, path, secretValue)
	if err != nil {
		return ErrSecretMigration{
			Path:  path,
			Cause: err,
		}
	}

	// Track the migration
	migrated := MigratedSecret{
		ConfigPath:  path,
		KMSPath:     kmsPath,
		Strategy:    strategy,
		OriginalURI: maskURI(uri),
	}
	result.Migrated = append(result.Migrated, migrated)

	// Track auto-generated secrets separately
	if strategy == StrategyAutoGen {
		result.AutoGenerated = append(result.AutoGenerated, path)
	}

	m.logger.Info("migrated secret to local KMS",
		"config_path", path,
		"kms_path", kmsPath,
		"strategy", strategy,
	)

	return nil
}

// processSlice handles slice fields that may contain structs with secrets.
func (m *SecretManager) processSlice(ctx context.Context, field reflect.Value, path string, result *MigrationResult) error {
	for i := 0; i < field.Len(); i++ {
		elem := field.Index(i)
		elemPath := fmt.Sprintf("%s[%d]", path, i)

		switch elem.Kind() {
		case reflect.Struct:
			if err := m.walkStruct(ctx, elem, elemPath, result); err != nil {
				return err
			}
		case reflect.Ptr:
			if !elem.IsNil() && elem.Elem().Kind() == reflect.Struct {
				if err := m.walkStruct(ctx, elem.Elem(), elemPath, result); err != nil {
					return err
				}
			}
		case reflect.String:
			if err := m.processStringField(ctx, elem, reflect.StructField{}, elemPath, false, result); err != nil {
				result.Errors = append(result.Errors, ErrFieldProcessing{
					Path:  elemPath,
					Cause: err,
				})
			}
		}
	}
	return nil
}

// processMap handles map fields that may contain structs with secrets.
func (m *SecretManager) processMap(ctx context.Context, field reflect.Value, path string, result *MigrationResult) error {
	iter := field.MapRange()
	for iter.Next() {
		key := iter.Key()
		val := iter.Value()

		var keyStr string
		if key.Kind() == reflect.String {
			keyStr = key.String()
		} else {
			keyStr = fmt.Sprintf("%v", key.Interface())
		}
		elemPath := fmt.Sprintf("%s.%s", path, keyStr)

		switch val.Kind() {
		case reflect.Struct:
			// Maps return non-addressable values, so we need to make a copy
			valCopy := reflect.New(val.Type()).Elem()
			valCopy.Set(val)
			if err := m.walkStruct(ctx, valCopy, elemPath, result); err != nil {
				return err
			}
		case reflect.Ptr:
			if !val.IsNil() && val.Elem().Kind() == reflect.Struct {
				if err := m.walkStruct(ctx, val.Elem(), elemPath, result); err != nil {
					return err
				}
			}
		case reflect.String:
			uri := val.String()
			if uri != "" && m.isSecretURI(uri) {
				// Note: We cannot modify map values directly through reflection
				// This is logged as an error for the caller to handle
				result.Errors = append(result.Errors, ErrMapValueImmutable{
					Path: elemPath,
				})
			}
		}
	}
	return nil
}

// migrateToKMS stores a resolved secret in the local KMS.
func (m *SecretManager) migrateToKMS(ctx context.Context, configPath string, value []byte) (string, error) {
	// Build the KMS path from the config path
	kmsPath := m.buildKMSPath(configPath)

	metadata := map[string]string{
		"source":      "bootstrap",
		"config_path": configPath,
	}

	err := m.localKMS.StoreSecret(ctx, kmsPath, value, metadata)
	if err != nil {
		return "", err
	}

	return SchemeKMS + kmsPath, nil
}

// buildKMSPath constructs the KMS storage path from a config path.
func (m *SecretManager) buildKMSPath(configPath string) string {
	// Convert dot notation to path notation
	// e.g., "kms.backends.tpm2.srk-auth" -> "config/kms/backends/tpm2/srk-auth"
	pathPart := strings.ReplaceAll(configPath, ".", "/")
	pathPart = strings.ReplaceAll(pathPart, "[", "/")
	pathPart = strings.ReplaceAll(pathPart, "]", "")

	if m.configPath != "" {
		return m.configPath + "/" + pathPart
	}
	return pathPart
}

// isSecretURI returns true if the string appears to be a secret URI.
func (m *SecretManager) isSecretURI(s string) bool {
	return strings.HasPrefix(s, SchemeKMS) ||
		strings.HasPrefix(s, SchemeRemoteKMS) ||
		strings.HasPrefix(s, SchemeAutoGen) ||
		strings.HasPrefix(s, SchemeEnv) ||
		strings.HasPrefix(s, SchemeEncrypted) ||
		strings.HasPrefix(s, SchemeDynamic) ||
		strings.HasPrefix(s, SchemeXKMS)
}

// IsSecretURI returns true if the string appears to be a secret URI.
// This is the exported version for use by callers that need to check
// whether a value has already been migrated.
func IsSecretURI(s string) bool {
	return strings.HasPrefix(s, SchemeKMS) ||
		strings.HasPrefix(s, SchemeRemoteKMS) ||
		strings.HasPrefix(s, SchemeAutoGen) ||
		strings.HasPrefix(s, SchemeEnv) ||
		strings.HasPrefix(s, SchemeEncrypted) ||
		strings.HasPrefix(s, SchemeDynamic) ||
		strings.HasPrefix(s, SchemeXKMS)
}

// detectStrategy determines the resolution strategy from a URI.
func (m *SecretManager) detectStrategy(uri string) string {
	switch {
	case strings.HasPrefix(uri, SchemeKMS):
		return StrategyKMS
	case strings.HasPrefix(uri, SchemeRemoteKMS):
		return StrategyRemoteKMS
	case strings.HasPrefix(uri, SchemeAutoGen):
		return StrategyAutoGen
	case strings.HasPrefix(uri, SchemeEnv):
		return StrategyEnv
	case strings.HasPrefix(uri, SchemeEncrypted):
		return StrategyEncrypted
	case strings.HasPrefix(uri, SchemeDynamic):
		return StrategyDynamic
	case strings.HasPrefix(uri, SchemeXKMS):
		return StrategyXKMS
	default:
		return StrategyLiteral
	}
}

// buildFieldPath constructs the dot-notation path for a struct field.
func buildFieldPath(parentPath string, field reflect.StructField) string {
	// Use yaml tag if available, otherwise json tag, otherwise field name
	name := field.Tag.Get("yaml")
	if name == "" {
		name = field.Tag.Get("json")
	}
	if name == "" {
		name = field.Tag.Get("mapstructure")
	}

	// Handle tag options (e.g., "name,omitempty" or ",omitempty")
	if idx := strings.Index(name, ","); idx != -1 {
		name = name[:idx]
	}

	// If name is empty after stripping options, use field name
	if name == "" {
		name = strings.ToLower(field.Name)
	}

	// Skip "-" tagged fields
	if name == "-" {
		return ""
	}

	if parentPath == "" {
		return name
	}
	return parentPath + "." + name
}

// ExpandShortKMSPath expands a short KMS path that does not start with
// "tenants/" into a fully-qualified keyspace path by prepending
// tenants/{tenantID}/nodes/{nodeID}/secrets/. This allows config files
// to use compact URIs like kms://bmc/password while the resolver maps
// them to the full multi-tenant keyspace.
//
// If the path already starts with "tenants/", it is returned unchanged.
// If tenantID or nodeID is empty, the path is returned unchanged to
// avoid producing malformed paths.
func ExpandShortKMSPath(path, tenantID, nodeID string) string {
	if strings.HasPrefix(path, "tenants/") {
		return path
	}
	if tenantID == "" || nodeID == "" {
		return path
	}
	return "tenants/" + tenantID + "/nodes/" + nodeID + "/secrets/" + path
}

// maskURI masks sensitive parts of a URI for logging.
func maskURI(uri string) string {
	// Keep the scheme and path structure, but mask the actual secret data
	for _, scheme := range []string{
		SchemeKMS, SchemeRemoteKMS, SchemeAutoGen,
		SchemeEnv, SchemeEncrypted, SchemeDynamic, SchemeXKMS,
	} {
		if strings.HasPrefix(uri, scheme) {
			return scheme + "***"
		}
	}
	// If it's a literal value that looks sensitive, mask it entirely
	if len(uri) > 0 {
		return "***"
	}
	return uri
}
