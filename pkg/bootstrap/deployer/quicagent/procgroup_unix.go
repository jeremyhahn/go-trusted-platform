//go:build unix

package quicagent

import (
	"os/exec"
	"syscall"
)

// killProcessGroupOnCancel starts cmd in its own process group and makes
// context cancellation kill the whole group, so a child of the shell
// (sleep 300 in "sleep 300; echo done") does not outlive the operation
// holding the output pipes open.
func killProcessGroupOnCancel(cmd *exec.Cmd) {
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	cmd.Cancel = func() error {
		return syscall.Kill(-cmd.Process.Pid, syscall.SIGKILL)
	}
}
