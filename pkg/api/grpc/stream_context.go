package grpc

import (
	"context"

	"google.golang.org/grpc"
)

// wrappedServerStream wraps grpc.ServerStream to provide a modified context.
// It used to live in the Linux-only Unix credentials file, which left the
// OIDC stream interceptor unbuildable elsewhere; the peer-credential code
// now lives in pkg/util/peercred and carries its own copy.
type wrappedServerStream struct {
	grpc.ServerStream
	ctx context.Context
}

// Context returns the wrapped context.
func (w *wrappedServerStream) Context() context.Context {
	return w.ctx
}
