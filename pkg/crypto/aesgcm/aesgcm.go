package aesgcm

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"encoding/hex"
	"io"
)

// Wire-format sizes of the blob Seal produces: nonce || ciphertext || tag.
// crypto/cipher fixes both for GCM-with-random-nonce and does not export them
// (its NonceSize reports 0, since the nonce travels inside the ciphertext).
// A sealed blob is therefore NonceSize + len(plaintext) + TagSize bytes.
const (
	NonceSize = 12
	TagSize   = 16
)

// AESGCM is the platform's one AES-GCM implementation. pkg/registry seals
// layer content and wraps data-encryption keys through it (#248); keep it the
// only place in the platform that constructs a GCM cipher.
type AESGCM struct {
	random io.Reader
}

// NewAESGCM returns an AESGCM whose GenerateKey draws from random, defaulting
// to crypto/rand.Reader when random is nil. The reader does not feed Seal:
// its nonce is generated by the cipher itself (see Seal).
func NewAESGCM(random io.Reader) AESGCM {
	if random == nil {
		random = rand.Reader
	}
	return AESGCM{
		random: random,
	}
}

// GenerateKey returns a 32-character hex-encoded 16-byte random value. It draws
// from the configured entropy source, which NewAESGCM defaults to
// crypto/rand.Reader — the source it always used in practice, since every
// caller passes rand.Reader.
func (a AESGCM) GenerateKey() []byte {
	bytes := make([]byte, 16)
	if _, err := io.ReadFull(a.random, bytes); err != nil {
		panic(err.Error())
	}
	return []byte(hex.EncodeToString(bytes))
}

// Seal encrypts data under key with AES-GCM and returns nonce || ciphertext ||
// tag as a single blob.
//
// The nonce is generated by the cipher itself rather than drawn from this
// type's entropy reader, and is carried inside the returned blob rather than
// beside it. cipher.NewGCM — which takes a caller-supplied nonce — is rejected
// outright under GODEBUG=fips140=only, so an explicit-nonce construction cannot
// run in a FIPS build at all (#209). A single self-framing blob also removes
// the caller's opportunity to pair a ciphertext with the wrong nonce.
func (a AESGCM) Seal(key, data, additionalData []byte) ([]byte, error) {

	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, err
	}

	aesgcm, err := cipher.NewGCMWithRandomNonce(block)
	if err != nil {
		return nil, err
	}

	return aesgcm.Seal(nil, nil, data, additionalData), nil
}

// Open decrypts a blob produced by Seal — nonce || ciphertext || tag — under
// key, verifying additionalData. The nonce is read from the blob's prefix, so
// there is no separate nonce parameter to get wrong. A blob too short to hold
// a nonce and a tag is refused with ErrCiphertextTooShort before any
// decryption is attempted, rather than with the standard library's opaque
// authentication failure.
func (a AESGCM) Open(key, ciphertext, additionalData []byte) ([]byte, error) {
	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, err
	}
	aesgcm, err := cipher.NewGCMWithRandomNonce(block)
	if err != nil {
		return nil, err
	}
	if len(ciphertext) < NonceSize+TagSize {
		return nil, ErrCiphertextTooShort{Length: len(ciphertext)}
	}
	return aesgcm.Open(nil, nil, ciphertext, additionalData)
}
