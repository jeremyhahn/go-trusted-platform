package aesgcm

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
)

var (
	ErrInvalidNonce         = errors.New("crypto/cipher: incorrect nonce length given to GCM")
	ErrMessageTooLarge      = errors.New("crypto/cipher: message too large for GCM")
	ErrInvalidBufferOverlap = errors.New("crypto/cipher: invalid buffer overlap")
)

// Wire-format sizes of the blob Seal produces: nonce || ciphertext || tag.
// crypto/cipher fixes both for GCM-with-random-nonce and does not export them
// (its NonceSize reports 0, since the nonce travels inside the ciphertext).
const (
	nonceSize = 12
	tagSize   = 16
)

type AESGCM struct {
	random io.Reader
}

// AES CGM encrypter / decrypter. Accepts a logger and optional source of
// entropy, such as the TPM or an HSM. A randomly generated nonce, not exceeding
// 96 bits, is automatically generated to add nonce misuse-resistance.
//
// In addition, this code wraps the panic that the Golang runtime throws
// when a nonce is incorrect, a message is too large, or a buffer overlap is
// detected, and returns a recoverable error instead of allowing it to crash
// servers.
// https://pkg.go.dev/crypto/cipher
// https://datatracker.ietf.org/doc/html/rfc8452
func NewAESGCM(random io.Reader) AESGCM {
	if random == nil {
		random = rand.Reader
	}
	return AESGCM{
		random: random,
	}
}

// Generates and returns an AES-256 32 byte key
// encoded to hexadecimal
// GenerateKey returns a 32-character hex-encoded 16-byte random value. It draws
// from the configured entropy source, which NewAESGCM defaults to
// crypto/rand.Reader — the source it always used in practice, since every
// caller passes rand.Reader.
func (a AESGCM) GenerateKey() []byte {
	bytes := make([]byte, 16)
	if _, err := io.ReadFull(a.random, bytes); err != nil {
		panic(err.Error())
	}
	return []byte(hex.EncodeToString(bytes))
}

// Seal the provided plain-test and "additional data" data
// with the specified encryption key, using AES256 in GCM mode,
// which provides authenticated encryption. Returns the ciphertext
// and a nonce, used as the Initialization Vector for the AES
// counter mode.
// Seal encrypts data under key with AES-GCM and returns nonce || ciphertext ||
// tag as a single blob.
//
// The nonce is generated by the cipher itself rather than drawn from this
// type's entropy reader, and is carried inside the returned blob rather than
// beside it. cipher.NewGCM — which takes a caller-supplied nonce — is rejected
// outright under GODEBUG=fips140=only, so an explicit-nonce construction cannot
// run in a FIPS build at all (#209). A single self-framing blob also removes
// the caller's opportunity to pair a ciphertext with the wrong nonce.
func (a AESGCM) Seal(key, data, additionalData []byte) ([]byte, error) {

	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, err
	}

	aesgcm, err := cipher.NewGCMWithRandomNonce(block)
	if err != nil {
		return nil, err
	}

	return aesgcm.Seal(nil, nil, data, additionalData), nil
}

// Seal encrypts and authenticates plaintext, authenticates the
// additional data and
// Open decrypts a blob produced by Seal — nonce || ciphertext || tag — under
// key, verifying additionalData. The nonce is read from the blob's prefix, so
// there is no separate nonce parameter to get wrong.
func (a AESGCM) Open(key, ciphertext, additionalData []byte) (plaintext []byte, err error) {
	block, err := aes.NewCipher(key)
	if err != nil {
		return nil, err
	}
	aesgcm, err := cipher.NewGCMWithRandomNonce(block)
	if err != nil {
		return nil, err
	}
	defer func() {
		// Recover from panic to keep prevent servers from crashing
		if r := recover(); r != nil {
			err = &MessageError{Msg: fmt.Sprintf("%s", r)}
		}
	}()
	plaintext, err = aesgcm.Open(nil, nil, ciphertext, additionalData)
	if err != nil {
		return nil, err
	}

	return plaintext, nil
}
